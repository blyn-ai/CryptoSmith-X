-- ============================================================================
-- CryptoSmith X — миграция 0056: у bybit-spot появляется адрес, и он ТОТ ЖЕ,
-- что у перпов.
--
-- api.bybit.com обслуживает обе поверхности, поэтому после 0054 оба сегмента
-- получают ОДИН гейт — так и задумано. Своего потолка спот не просит:
-- request_budget_per_s остаётся NULL, и оба сегмента живут под потолком биржи.
--
-- Это противоположный Binance случай, и обе половины нужны, чтобы ключ на хост
-- имел смысл: там два хоста с независимыми потолками, здесь один хост с общим.
-- Ключ на биржу был бы неверен для первого, ключ на сегмент — для второго.
--
-- Замерено на живой площадке 2026-09-13:
--
--     instruments-info?category=spot   538 строк   285 КБ   одна страница
--     tickers?category=spot            538 строк   159 КБ
--
-- Снимок закрывается одним вызовом, как и на перпах. Ёмкости спот не добавляет
-- — он добавляет инструментов под уже существующий потолок.
-- ============================================================================

update segment
   set base_url = 'https://api.bybit.com',
       updated_at = now(),
       updated_by = '0056'
 where code = 'bybit-spot';
