-- ============================================================================
-- CryptoSmith X — миграция 0036: бюджеты запросов становятся измеренными.
--
-- exchange.request_budget_source умеет значение 'measured' с 0021, и до сих пор
-- им не была помечена ни одна строка: два числа стояли как 'documented', два
-- как 'assumed', и все четыре расходились с тем, что площадки на самом деле
-- выдерживают. Эта миграция ставит числа, полученные пробой, и записывает
-- рядом, чем именно они получены — чтобы следующий человек не мерил заново.
--
-- Форма пробы во всех случаях одна: N параллельных запросов x пауза x раундов,
-- РАЗНЫЕ символы внутри раунда. Число, полученное повторением одного URL, не
-- считается: край отдаёт из кеша и меряется кеш, а не потолок.
--
-- ----------------------------------------------------------------------------
-- Что измерено
-- ----------------------------------------------------------------------------
-- WEEX (мерено ранее, см. plans/collection-policy.md §5): срыв на ~224 запросах
--   за ~6 с, то есть ~37 rps, воспроизвёлся дважды с точностью до раунда. Бан
--   ~10 с, совпал с их документацией. 32 параллельных держатся семь раундов —
--   ограничение по ОКНУ, не по одновременности. Ставим 30: запас ~20 % под
--   измеренным. Прежние 200 'documented' — число, которого нет ни в одном из
--   двух источников, на которые ссылалась 0021 (разбор в plans/exchange-roadmap.md);
--   вшестеро выше измеренного, и это была единственная строка, где мы верили
--   цифре, которую никто не видел.
--
-- Binance USDⓈ-M (мерено ранее): 512 запросов при 64 параллельных — ноль
--   отказов. Документированный бюджет 2400 weight/мин = 40 rps при весе 1;
--   openInterest весит 1, свечи 1..10 по limit. Ставим 32, а не 40, именно
--   из-за свечей: 40 запросов в секунду по 10 weight — это 24000 weight/мин,
--   вдесятеро над бюджетом. 32 оставляет запас на неравномерный вес.
--
-- Kraken Futures (мерено 2026-09-08, эта миграция): 32 параллельных x 0,5 с x
--   16 раундов, затем 32 x БЕЗ ПАУЗЫ x 24 раунда по /derivatives/api/v4/
--   historicalfundingrates — 1280 запросов, НОЛЬ отказов, раунд 0,62–1,28 с,
--   устойчиво ~40 rps. Потолок не найден: мы измерили не его, а то, что до
--   этой отметки площадка не спорит. Документация публичного лимита не даёт
--   вообще — сказано лишь, что у публичных эндпоинтов «нет стоимости», что не
--   то же самое, что «нет предела»: обе наши ручки перечисляют apiLimitExceeded
--   среди своих ошибок. Ставим 32 — ниже измеренного, с тем же запасом.
--
-- Hyperliquid (мерено 2026-09-08, эта миграция): та же проба по info/l2Book —
--   1280 запросов, ноль отказов, раунд 1,00–2,14 с, устойчиво ~27 rps.
--
--   И ЗДЕСЬ ИЗМЕРЕННОЕ РАСХОДИТСЯ С ДОКУМЕНТИРОВАННЫМ, поэтому число тут
--   отдельное и меньше прочих. Hyperliquid публикует бюджет НЕ в запросах, а в
--   весе: 1200 weight/мин на IP, где l2Book стоит 2, а всё прочее в info — 20,
--   причём candleSnapshot добавляет ещё вес за каждые 60 отданных баров. То
--   есть в пересчёте на l2Book документация разрешает 10 rps, а на
--   candleSnapshot — 1 rps. Проба прошла втрое над первым порогом без единого
--   отказа, но одним числом «запросов в секунду» весовой бюджет не выражается
--   в принципе: наш ограничитель считает запросы, а площадка считает вес.
--   Ставим 20 — вдвое ниже измеренного и в границах того, что уже происходило
--   (прежние 10 'assumed' на свечах и так давали 200 weight/с). Это осознанный
--   компромисс, а не вывод из документации, и он записан здесь именно потому,
--   что его придётся пересмотреть, когда ограничитель научится весу. Пока не
--   научился — эта строка единственная, где 'measured' стоит рядом с известным
--   расхождением.
--
-- ----------------------------------------------------------------------------
-- Почему max_concurrent_requests = 32 у всех
-- ----------------------------------------------------------------------------
-- Прежние 8/8/8/4 не имели источника вообще — ни документированного, ни
-- измеренного. Все замеры выше сделаны ровно при 32 одновременных, и именно
-- одновременность делает проход быстрым: у Kraken funding 206 символов шли 74 с
-- строго по одному, ~360 мс на вызов; те же 360 мс при 32 в полёте дают ~2,5 с.
-- Ограничение по темпу остаётся отдельным — VenueGate держит и то, и другое.
-- Верхняя граница колонки (0021) — 64, так что 32 в неё укладывается.
--
-- Значения read-only для приложения: их читает DbSettings при старте воркера.
-- ============================================================================

