-- ============================================================================
-- CryptoSmith X — миграция 0046: партиции, в которые только дописывают,
-- перестают ждать вакуума, которого не будет.
--
-- НАЙДЕНО ЗАМЕРОМ, а не рассуждением. Страница актива стала отвечать за 6.8-8.7 с
-- и временами падать по таймауту чтения. Разложение по запросам дало виновника
-- сразу: выборка истории снимков за сутки — 7 453 строки — шла 1929 мс. План при
-- этом ПРАВИЛЬНЫЙ: обрезка партиций работает, index-only scan выбран. Но в нём
-- стояло `Heap Fetches: 7452` — то есть «index-only» ходил в кучу за каждой
-- строкой. Ручной `vacuum (analyze)` на партиции: 1929 мс → 11.5 мс, в 167 раз,
-- и страница вернулась к 2.1-2.7 с.
--
-- ПОЧЕМУ АВТОВАКУУМ НЕ ПРИХОДИЛ. `market_snapshot_2026_09`: 14 151 487 живых
-- строк, мёртвых — 1806, последний автовакуум 2026-09-07, четыре дня назад.
-- Это не сбой автовакуума, это его штатное поведение: порог считается ОТ
-- МЁРТВЫХ строк (20% таблицы), а в таблицу, куда только дописывают и ничего не
-- обновляют, мёртвых не приходит почти никогда. Порог в 2.8 млн не будет достигнут
-- ни разу. Тем временем каждая новая страница остаётся не отмеченной в visibility
-- map — и index-only scan обязан лезть в кучу, чтобы проверить видимость.
--
-- То есть вакуум здесь нужен НЕ ДЛЯ УБОРКИ МУСОРА, которого нет, а ради карты
-- видимости. Именно для этого в PG13 появился отдельный порог по ВСТАВКАМ, и
-- он ровно про такие таблицы.
--
-- Порог 200 000 строк: партиция снимков набирает столько примерно за сутки на
-- сегодняшних ~420 собираемых инструментах, так что карта обновляется раз в день
-- и не чаще. Меньше — вакуум ходил бы по 14-миллионной партиции постоянно;
-- больше — деградация успевала бы стать заметной, а она нарастает молча: никакой
-- ошибки, просто страница медленнее с каждым днём месяца.
--
-- ЗАЧЕМ В ФУНКЦИЮ, А НЕ ALTER ПО СПИСКУ. Партиции заводятся помесячно
-- (Partitions.EnsureCurrentAndNextAsync), то есть первого числа каждого месяца
-- появляется новая — и настройка, проставленная сегодня руками, на неё не
-- попадёт. Через месяц всё вернулось бы, и искать пришлось бы заново. Настройка
-- ставится ТАМ, ГДЕ ПАРТИЦИЯ РОЖДАЕТСЯ.

create or replace function public.create_month_partition(parent regclass, month date)
 returns void
 language plpgsql
as $function$
declare
    start_date date := date_trunc('month', month)::date;
    end_date   date := (start_date + interval '1 month')::date;
    part_name  text := format('%s_%s', parent::text, to_char(start_date, 'YYYY_MM'));
begin
    execute format(
        'create table if not exists %I partition of %s for values from (%L) to (%L)',
        part_name, parent, start_date, end_date
    );

    -- Вакуум по ВСТАВКАМ. Без него автовакуум на append-партицию не приходит
    -- вовсе — см. шапку файла: мёртвых строк в ней нет, а порог считается по ним.
    -- Ставится на каждую партицию при создании, потому что через месяц будет
    -- следующая, и ей нужно то же самое.
    execute format(
        'alter table %I set (autovacuum_vacuum_insert_threshold = 200000, '
        || 'autovacuum_vacuum_insert_scale_factor = 0)',
        part_name
    );
end
$function$;


-- Существующим партициям — то же самое, разово: функция выше починит только те,
-- что ещё не созданы. Список берётся из каталога, а не перечисляется руками,
-- чтобы ничего не забыть и чтобы миграция не устарела при добавлении таблицы.
do $$
declare
    part record;
begin
    for part in
        select c.relname
          from pg_class c
          join pg_inherits i on i.inhrelid = c.oid
          join pg_class p on p.oid = i.inhparent
         where p.relkind = 'p' and c.relkind = 'r'
    loop
        execute format(
            'alter table %I set (autovacuum_vacuum_insert_threshold = 200000, '
            || 'autovacuum_vacuum_insert_scale_factor = 0)',
            part.relname);
    end loop;
end
$$;
