-- ============================================================================
-- CryptoSmith X — миграция 0039: volume_quote на market_candle.
--
-- Фаза 4 плана владельца (plans/prompt-collect-everything.md), пункт 5 — единственный
-- пункт фазы, требующий схемы.
--
--
-- ----------------------------------------------------------------------------
-- Почему это не то же самое обсуждение, что уже было дважды отклонено
-- ----------------------------------------------------------------------------
-- 0001 отвергло это же поле с причиной «нет у Hyperliquid и Kraken; для оценки
-- ликвидности есть turnover_24h на снапшоте». 0035 §D.2 подтвердило отказ
-- дословно: «причина не изменилась — эта серия её не переоткрывает».
--
-- Эта серия — открывает, и вот почему причина не держится: по тому же
-- рассуждению («нет у части площадок») в схеме не было бы ни oi_quote
-- (0001), ни volume_24h_quote/turnover_24h — а они есть, с NULL там, где
-- площадка их не отдаёт. «Нет у всех» никогда не было причиной не заводить
-- поле нигде в этой схеме, кроме этого одного случая. Настоящая причина 0001
-- была другой и честной: у поля не было читателя, а свеча всегда
-- восстановима бэкфиллом — значит не срочно. Пункт 1 этой же фазы уже трогает
-- писателя (market_candle получает received_at/known_from/source), так что
-- «когда всё равно трогаем писателя» — наступило.
--
-- ЕДИНИЦА. volume ("в единицах количества инструмента", комментарий 0001)
-- остаётся как есть. volume_quote — то же самое движение в валюте котировки,
-- независимая величина, а не производная (курс базовый/котировка внутри
-- минутного бара не постоянен, только на срезе тикера).
--
-- ПЛОЩАДКИ. Binance отдаёт его в kline[7], WEEX в kline[6] — оба сейчас берут
-- только kline[5] (base volume) и остальное выбрасывают. Kraken и Hyperliquid
-- этого поля не имеют вовсе на масштабе свечи — NULL, тем же способом, что и
-- oi_quote/volume_24h_base у площадок, которые их не отдают.
--
-- NULLABLE, без CHECK: тот же выбор, что 0030 сделала для восьми колонок
-- снапшота — площадка либо отдаёт число, либо честно нет.
-- ============================================================================

alter table market_candle
    add column volume_quote double precision;

comment on column market_candle.volume_quote is
    'Оборот бара в валюте котировки (в отличие от volume — в единицах количества '
    'инструмента, комментарий 0001). Binance: kline[7]; WEEX: kline[6]. NULL у Kraken и '
    'Hyperliquid — на масштабе свечи поле не отдаётся ни REST, ни WS ни у одной из этих '
    'площадок. Отменяет отказ 0001, подтверждённый 0035 §D.2, — обоснование в заголовке '
    'этого файла.';
