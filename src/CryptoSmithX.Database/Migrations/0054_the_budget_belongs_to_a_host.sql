-- ============================================================================
-- CryptoSmith X — миграция 0054: потолок запросов принадлежит ХОСТУ, и сегмент
-- может назвать свой.
--
-- 0019 положила бюджет на строку exchange, потому что два сегмента одной биржи
-- делят один IP-потолок. Для перпов это верно. Для спота — нет, и ломается это
-- в обе стороны сразу:
--
--   Binance   fapi.binance.com и api.binance.com — РАЗНЫЕ потолки, замерено:
--             2400 и 6000 весов в минуту. Ключ на биржу свёл бы два независимых
--             бюджета в один и урезал оба.
--   OKX       www.okx.com и для SWAP, и для SPOT. Двадцать одновременных
--             tickers на обе поверхности дали по десять успешных каждой — один
--             потолок на двоих. Ключ на сегмент выдал бы два гейта там, где
--             площадка считает один.
--   Bybit     api.bybit.com для обеих поверхностей — как OKX.
--   Kraken    futures.kraken.com и api.kraken.com — как Binance.
--
-- Ключ на биржу неверен для Binance и Kraken, ключ на сегмент неверен для OKX
-- и Bybit. Ключ на ХОСТ верен для всех четырёх замеров сразу, и 0053 пришла к
-- тому же выводу с другой стороны: она завела Coinbase International отдельной
-- строкой exchange именно потому, что у неё свой хост и свой потолок. Там это
-- решилось разделением биржи; здесь — тем, что ключ с самого начала тот, к
-- которому потолок и относится.
--
-- Колонка nullable и по умолчанию NULL: «этот сегмент ничего своего не просит,
-- возьми потолок биржи». Заполнять её имеет смысл ровно там, где хост сегмента
-- отличается от хоста остальных сегментов той же биржи.
--
-- ЧТО ДЕЛАЕТ ХАБ, когда два сегмента на ОДНОМ хосте назвали РАЗНЫЕ числа:
-- берёт МЕНЬШЕЕ и пишет предупреждение с обоими. Молча выбрать одно значило бы
-- применить потолок, которого не задавал никто.
-- ============================================================================

alter table segment
    add column request_budget_per_s int
        check (request_budget_per_s >= 1 and request_budget_per_s <= 10000);

comment on column segment.request_budget_per_s is
    'Потолок запросов в секунду ДЛЯ ХОСТА ЭТОГО СЕГМЕНТА. NULL — брать с биржи. '
    'Заполнять там, где хост сегмента отличается от хоста остальных сегментов той же '
    'биржи: fapi.binance.com и api.binance.com — разные потолки, www.okx.com — один '
    'на SWAP и SPOT. Гейт ключуется на хост из base_url; два сегмента на одном хосте '
    'делят один гейт, и если оба назвали своё число, берётся меньшее.';
