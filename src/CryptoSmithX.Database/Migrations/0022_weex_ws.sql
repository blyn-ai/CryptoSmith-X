-- ============================================================================
-- 0022 — у WEEX появляется WebSocket: стакан идёт с сокета, а не обходом по
-- символу.
--
-- Это отмена решения, принятого в 0011 и в коммите 100f605. Отменять чужое
-- решение полагается с объяснением, почему оно было верным тогда и почему
-- перестало быть верным сейчас, — иначе через год кто-то отменит эту миграцию
-- с той же лёгкостью.
--
-- ---------------------------------------------------------------------------
-- Что говорило старое решение
-- ---------------------------------------------------------------------------
-- 0011 оставил `ws_url` пустым и записал прямо: «ws_url null здесь означает не
-- „забыли“, а решение фазы 2 не делать сейчас». Причин было названо две:
--
--   1. У WEEX «другой протокол дельт — диапазоны версий, а не единый seq».
--      Речь про контрактный V2: дельта несла startVersion/endVersion, и клиент
--      обязан был склеивать цепочку диапазонов.
--   2. Нет способа сузить подписку: ~1000 инструментов, у всех collect=true.
--
-- Обе были верны. Первая перестала существовать: WEEX запустил контрактный V3
-- 18 марта 2026 и объявил V2 снятым с поддержки. V3 — протокол в форме Binance
-- с полями U/u, и правило у него своё, третье: `U` кадра должно быть РАВНО `u`
-- предыдущего кадра, ровно, без «плюс один» как у Binance. Что важнее для нас:
-- снапшот книги WEEX отдаёт по самому сокету, поэтому гонки «REST-затравка
-- против первой дельты», которая у Binance является главным источником ошибок
-- в этой части, здесь нет вовсе.
--
-- Вторая причина никуда не делась, но перестала быть возражением: обход стакана
-- по одному символу — это и есть проблема, а не подписка. На проде проход по
-- 1005 инструментам занимал 361 с при такте 60 с (реальная каденция 421 с,
-- загрузка цикла 86 %) на простаивающем хосте. Батча по depth у WEEX нет ни в
-- одном поколении API. Сокет отдаёт те же ~1000 книг одним соединением, и
-- нагрузка на нас становится потоком изменений вместо тысячи round-trip'ов.
--
-- ---------------------------------------------------------------------------
-- Почему на этот раз протокол не протухнет молча
-- ---------------------------------------------------------------------------
-- Вывод 100f605 про V2 был верным и умер тихо: он жил в тексте коммита, а не в
-- дереве, и ничто не заметило, что биржа сменила поколение API. Поэтому перед
-- единой строкой C# протокол снят с живого сокета и положен в
-- `tests/CryptoSmithX.MarketData.Connectors.Tests/Fixtures/weex-ws/`, а
-- `WeexWsProtocolTests` проверяет по этим кадрам именно то, что отличает V3 от
-- V2 и от Binance: отсутствие полей startVersion/endVersion/version и равенство
-- `U` предыдущему `u` на прогоне из 60 подряд идущих кадров. Следующая смена
-- поколения уронит тесты, а не тихо испортит книгу.
--
-- ---------------------------------------------------------------------------
-- Что именно меняет эта миграция
-- ---------------------------------------------------------------------------
-- Только конфигурацию, как и 0010 для Кракена. Ни одной новой таблицы, ни одной
-- строки рыночных данных: WS питает те же колонки depth через тот же
-- DepthCollector. Появление `ws_url` — это и есть переключатель: адаптер
-- поднимает фид, только когда адрес задан, и без него живёт чистым REST ровно
-- как раньше.
--
-- `transports_us` для пары (weex-futures, depth) переводится в 'rest,ws'.
-- Reconcile при старте объявляет это сам, из Capabilities адаптера, — строка
-- ниже нужна не вместо него, а чтобы состояние базы было верным СРАЗУ после
-- миграции, до первого запуска Хаба, и чтобы переход rest → rest,ws попал в
-- capability_log как событие с датой. Иначе изменение возможности площадки
-- выглядело бы так, будто оно случилось при ближайшем рестарте процесса.
--
-- ---------------------------------------------------------------------------
-- Что отвергнуто
-- ---------------------------------------------------------------------------
-- * Переводить на WS и `snapshot`. У публичного сокета WEEX нет канала верха
--   книги вовсе: @bookTicker, @markPrice и @miniTicker отклонены живым
--   сервером (записано в капчуре), и ни фандинга, ни открытого интереса сокет
--   не несёт. Снимок всё равно собирался бы из тех же батчевых REST-вызовов
--   плюс ещё одни часы, которые пришлось бы согласовывать, — а снимок и не был
--   дорогим: один батчевый вызов на всю биржу. Дорогим был стакан.
-- * Ставить `transports_venue`. Мы знаем, что предлагает биржа, гораздо шире
--   того, что берём мы (@trade, @kline, @ticker — всё это на сокете есть), но
--   эта колонка пуста во ВСЕХ строках базы, и заполнять её для одной клетки
--   означало бы сделать матрицу неравномерно правдивой. Это отдельная работа,
--   и она названа отдельной в плане.
-- * Заводить `ws_url` на уровне венью (`exchange`), а не сегмента. Сокет — это
--   поверхность площадки: у спота Kraken и у фьючерсов Kraken разные хосты. 0019
--   уже разложил это правильно, и колонка живёт на `segment` именно поэтому.
-- * Понижать бюджет запросов WEEX теперь, когда стакан ушёл с REST. Соблазн
--   есть, но 0021 сеял число из документации вендора, а не из нашей нагрузки;
--   потолок описывает, сколько нам МОЖНО, а не сколько мы берём. Меньше брать
--   мы и так стали.
-- ============================================================================

update segment
   set ws_url = 'wss://ws-contract.weex.com/v3/ws/public'
 where code = 'weex-futures';

-- Сегмент без адреса здесь означал бы, что переключатель не сработал, а
-- адаптер молча остался на REST — то есть миграция «прошла», не сделав ничего.
do $$
begin
    if not exists (select 1 from segment where code = 'weex-futures' and ws_url is not null) then
        raise exception 'weex-futures остался без ws_url: WS-фид не поднимется';
    end if;
end $$;

-- Переход возможности площадки — событие с датой, а не текущее значение поля.
insert into capability_log (segment_code, dataset_code, capability_key, old_value, new_value, source, changed_by, note)
select 'weex-futures', 'depth', 'transports_us', c.value, 'rest,ws', 'declared', '0022 migration',
       'Контрактный V3 у WEEX заменил V2: снапшот книги приходит по сокету, дельты чейнятся '
       || 'равенством U = предыдущему u. Возражение 100f605 против V2 больше не применимо.'
  from segment_dataset_capability c
 where c.segment_code = 'weex-futures' and c.dataset_code = 'depth' and c.capability_key = 'transports_us'
   and c.value is distinct from 'rest,ws';

update segment_dataset_capability
   set value = 'rest,ws', source = 'declared', valid_since = now(), filled_at = now(), filled_by = '0022 migration'
 where segment_code = 'weex-futures' and dataset_code = 'depth' and capability_key = 'transports_us';
