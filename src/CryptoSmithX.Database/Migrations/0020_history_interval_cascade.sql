-- ============================================================================
-- 0020 — такт хранения снапшотов переезжает в каскад клетки.
--
-- 0018 сделал его настройкой, но настройкой глобальной: одно число на весь
-- датасет snapshot, одинаковое для всех площадок. Пока площадки только
-- деривативные и их по одной на биржу, разницы нет. Со спотом она становится
-- главной: 14 500 инструментов спота против 1 500 перпов — при одном такте спот
-- съедает диск за месяцы, а перпы за годы, и решение «чем жертвуем» должно
-- приниматься по клетке, а не сразу по всем.
--
-- Форма повторяет уже существующий каскад интервала опроса, потому что это его
-- близнец:
--
--     interval_s          как часто СПРАШИВАЕМ
--     history_interval_s  как часто ОСТАВЛЯЕМ
--
-- Каскад: segment_dataset.history_interval_s → dataset.default_history_interval_s
-- → интервал опроса. Последняя ступень — не «значение не найдено», а осмысленный
-- ответ: чаще, чем спрашиваешь, оставить нельзя, поэтому «не задано» означает
-- «писать каждый проход». По той же причине действующее значение всегда
-- поднимается до интервала опроса: 5 при опросе раз в 10 секунд — это те же 10,
-- и метрика должна говорить 10, а не 5.
--
-- default_history_interval_s заполнен только у snapshot, и это признак самого
-- свойства: датасет различает опрос и хранение только если пишет не каждый
-- проход. У candles, funding и discovery каждый проход сохраняется целиком —
-- различать нечего. Форма редактирования показывает поле ровно тогда, когда у
-- датасета выставлено умолчание, иначе оператор задал бы значение, которое
-- коллектор не исполняет — ровно та ловушка, в которую 0014 уже попал с
-- ретеншеном (записываем, но не honouring, и приходится это документировать).
--
-- Побочно чинится латентный баг в RollupJob. Ожидаемое число строк за час там
-- считалось как 3600 / greatest(interval_s, 60), где 60 — зашитая константа,
-- случайно совпадавшая с глобальным history_interval_s. Стоило поставить
-- history_interval_s = 10 (а именно это и планируется на проде, когда приедут
-- диски), и market_metric_hour.expected_count продолжил бы говорить 60 при
-- реальных 360 строках — шестикратная ложь в единственной метрике, которая
-- отвечает на вопрос «этот час недосмотрен или рынок молчал». Теперь формула
-- читает тот же каскад, что и коллектор.
--
-- Значения не меняются: default_history_interval_s принимает ровно то, что
-- сейчас лежит в dataset_setting, поэтому на любой площадке миграция сама по
-- себе ничего не переключает.
-- ============================================================================

alter table dataset add column default_history_interval_s int;
alter table dataset add constraint dataset_default_history_interval_s_check
    check (default_history_interval_s > 0);

alter table segment_dataset add column history_interval_s int;
alter table segment_dataset add constraint segment_dataset_history_interval_s_check
    check (history_interval_s > 0);

-- Берём действующее значение, а не константу: на тесте и проде оно могло быть
-- уже поправлено руками, и миграция не должна это молча откатить.
update dataset
   set default_history_interval_s = coalesce(
       (select value::int from dataset_setting
         where dataset_code = 'snapshot' and key = 'history_interval_s'), 60)
 where code = 'snapshot';

delete from dataset_setting where dataset_code = 'snapshot' and key = 'history_interval_s';

comment on column dataset.default_history_interval_s is
    'Такт записи в историю по умолчанию, в секундах. NULL означает, что датасет не различает опрос '
    'и хранение — каждый проход сохраняется целиком. Непустое значение включает поле в форме '
    'редактирования клетки: оно объявляет, что коллектор этого датасета такт хранения исполняет.';

comment on column segment_dataset.history_interval_s is
    'Такт записи в историю для этой клетки, в секундах; NULL — взять умолчание датасета. '
    'Действующее значение никогда не меньше интервала опроса: чаще, чем спрашиваешь, не оставишь.';
