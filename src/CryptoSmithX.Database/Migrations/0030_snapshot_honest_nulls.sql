-- ============================================================================
-- CryptoSmith X — миграция 0030: снапшот перестаёт требовать все одиннадцать
-- полей сразу, и получает восемь новых наблюдений, которых сегодня не хватает,
-- чтобы полосы глубины и цену последней сделки можно было прочитать честно.
--
-- Эта миграция — первый файл фазы «только база» задачи Kraken full collection
-- (см. csx-db-only-phase.md в переписке с владельцем, 2026-09-08). Коннекторы,
-- сборщики, хаб, админка, Studio — не трогаем. Всё новое здесь остаётся NULL
-- до следующей фазы, и это не временная дыра: NULL значит «ещё не собиралось»,
-- ровно как 0028 уже сделал honest для funding_interval_hours.
--
--
-- ----------------------------------------------------------------------------
-- A. Почему снимаем NOT NULL
-- ----------------------------------------------------------------------------
-- Сегодня прочерк реализован как отказ писать строку целиком: комментарий на
-- market_snapshot_latest уже фиксирует правило неявно через NOT NULL на всех
-- одиннадцати полях тикера. Одного отсутствующего измерения (Kraken не
-- прислал funding в этом кадре, HL не открыл книгу для символа) хватает,
-- чтобы выбросить оставшиеся десять — вместе с bid/ask, которые были.
--
-- Владелец решил снять здесь и сейчас, не дожидаясь фазы 2 (см. вопросы
-- владельцу внизу файла): само снятие ничего не меняет, пока сборщики не
-- переписаны — SnapshotCollector.cs по-прежнему либо пишет полную строку,
-- либо не пишет её вовсе. Но откладывать снятие до момента, когда сборщик
-- уже готов писать NULL, означало бы добавлять новые nullable-колонки в
-- строку, где часть полей всё ещё NOT NULL по старой конвенции — то есть две
-- разные договорённости о том, что значит пустое поле, в одной таблице.
--
--
-- ----------------------------------------------------------------------------
-- B. Восемь новых колонок — зачем каждая
-- ----------------------------------------------------------------------------
-- Единица и часы — на каждую, как требует 0001.
--
--   venue_ts               — время тикера ПО БИРЖЕ. received_at остаётся
--                             ключом партиции и «нашими часами получения»;
--                             venue_ts — заявление биржи о том, когда кадр
--                             посчитан. NULL там, где биржа не проставляет
--                             отдельное время (WEEX, часть кадров Binance).
--
--   last_trade_at           — момент СДЕЛКИ, которой соответствует last_price.
--                             Без этого поля last_price — число без часов:
--                             неизвестно, устарело оно на секунду или на час,
--                             в отличие от received_at, которое говорит только
--                             когда МЫ его увидели. ВАЖНО для Hyperliquid: его
--                             адаptер сегодня пишет в last_price mid книги, а
--                             не цену сделки (HyperliquidMarketData.cs:108-109,
--                             комментарий класса называет это «the closest
--                             honest proxy» — на этом масштабе у venue нет
--                             батч-поля последней сделки). У HL сделки за
--                             этим числом нет, поэтому last_trade_at обязан
--                             оставаться NULL всегда, а не «неизвестно» —
--                             это не пропуск измерения, это отсутствие
--                             события, которое колонка описывает. Сборщик
--                             фазы 2 не должен путать это с недостающими
--                             данными и подставлять venue_ts вместо него.
--
--   funding_rate_predicted  — прогноз СЛЕДУЮЩЕГО периода. Kraken присылает
--                             (funding_rate_prediction в тикере), большинство
--                             остальных — нет. Не путать с funding_rate —
--                             тот про уже наступивший период.
--
--   next_funding_at         — момент следующего платежа, КАК ПРИСЛАЛА БИРЖА.
--                             Отвергнут в 0001 как вычислимый из интервала —
--                             возвращается в другом статусе: это не таймер,
--                             который считаем мы, а факт, который Kraken
--                             прислал в кадре (next_funding_rate_time). Там,
--                             где биржа не присылает, поле NULL, а не
--                             funding_interval_hours-арифметика — вычисленное
--                             значение легко перепутать с наблюдённым, если
--                             оба лежат в одной колонке без пометки.
--
--   volume_24h_base         — скользящие 24 ч оборота в BASE (единицах
--                             инструмента). turnover_24h остаётся оборотом в
--                             QUOTE — они не взаимно выводимы без цены на
--                             каждый момент внутри окна, а не только на его
--                             конец.
--
--   depth_ref               — mid, ОТ КОТОРОГО отсчитаны полосы 10/25/50 bps.
--                             Без него полосы невоспроизводимы: bps — это
--                             расстояние от какой-то цены, а не абсолютный
--                             уровень, и если эта цена не сохранена, число
--                             «depth_bid_25bps = 40000» нельзя проверить и
--                             нельзя пересчитать в другую цену отсчёта.
--
--   book_reach_bid,
--   book_reach_ask          — докуда РЕАЛЬНО видна книга, в bps от depth_ref,
--                             по каждой стороне отдельно (стороны книги не
--                             симметричны). Без этого поля пустая полоса
--                             25bps неотличима от «в книге правда пусто на
--                             этом расстоянии» и от «мы запросили только 10
--                             уровней и дальше книги не видели». Правило
--                             чтения: полоса b честна, если book_reach ≥ b;
--                             пустая сторона книги (нет ни одного уровня) —
--                             это 0, а не NULL — измерение состоялось и дало
--                             результат «пусто»; книги не было вовсе (депт не
--                             собирался в этом кадре) — NULL вместе с
--                             depth_ref, потому что тогда неизвестна и точка
--                             отсчёта.
--
--
-- ----------------------------------------------------------------------------
-- Чего здесь нет и почему
-- ----------------------------------------------------------------------------
--   * Переписывания SnapshotCollector.cs. Он по-прежнему либо не пишет
--     строку, либо пишет её полностью NOT NULL-совместимой — фаза 2.
--   * next_funding_at как вычисление из funding_interval_hours. Это ДРУГОЕ
--     поле по смыслу (наблюдение биржи, не наш расчёт) — вычислимую версию,
--     если понадобится, потребитель посчитает на чтении сам, как считает
--     остальные производные вещи (spread, OI notional — комментарий на
--     market_snapshot).
--   * Переименований (last_price, turnover_24h). Отдельный вопрос с другой
--     ценой — читатели и писатели, которых эта фаза не трогает.
-- ============================================================================


