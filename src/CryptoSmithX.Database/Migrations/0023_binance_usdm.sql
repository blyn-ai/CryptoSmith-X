-- ============================================================================
-- 0023 — у binance-usdm наконец появляется адаптер, и вместе с ним честный
-- бюджет запросов.
--
-- Строка сегмента `binance-usdm` живёт в базе с 0001. Всё это время в консоли
-- площадка выглядела заведённой, а `ExchangeWorker.Build()` не имел для неё
-- ветки вовсе и бросал исключение: «adapter does not exist yet». Каталог
-- `Connectors/Binance/` не существовал. То есть база утверждала одно, а код —
-- другое, и заметить это можно было только включив площадку.
--
-- Эта миграция закрывает конфигурационную часть: адрес REST, адрес сокета,
-- бюджет запросов, такт стакана и алиасы активов с множителем в имени.
--
-- ---------------------------------------------------------------------------
-- 1. Бюджет: почему число из 0021 было неверным и откуда взято новое
-- ---------------------------------------------------------------------------
-- 0021 засеял бирже 20 req/s с источником 'assumed' и прямой оговоркой
-- «адаптера пока нет». Оговорка была честной, а число — опасным, и вот почему.
--
-- Binance меряет бюджет НЕ в запросах, а в весах: 2400 весов в минуту на IP.
-- Это не пересказ документации — число прочитано живьём из поля `rateLimits`
-- ответа GET /fapi/v1/exchangeInfo сегодня, вместе с весом каждого вызова,
-- снятым из заголовка `x-mbx-used-weight-1m`:
--
--     exchangeInfo                      1     fundingInfo                  0
--     ticker/bookTicker (без symbol)    5     premiumIndex (без symbol)    6
--     ticker/24hr       (без symbol)   40     openInterest (на символ)     1
--     klines limit<=100                 1     klines limit=1500           10
--     depth  limit=100                  5     depth  limit=500            10
--     fundingRate                       0
--
-- Плоский потолок в запросах не может выразить такую сетку — 0021 отверг
-- бюджет в весах сознательно, и это решение здесь не отменяется. Но раз потолок
-- один на все вызовы, выбирать его надо от САМОГО ДОРОГОГО из тех, что мы
-- делаем часто, а не наугад. Самый дорогой частый вызов — depth веса 5. Отсюда
-- 2400 / 5 = 480 запросов в минуту = 8 req/s как абсолютный предел, если бы всё
-- было стаканом. Реальная смесь дешевле, поэтому потолок поднят до 16 req/s, и
-- вот арифметика, которая делает это безопасным при тактах ниже:
--
--     стакан    ~570 символов / 300 с × вес 5 =  570 весов/мин
--     свечи     ~570 символов /  60 с × вес 1 =  570 весов/мин
--     снапшот   3 вызова      /  10 с × вес 55/3 = 330 весов/мин
--     открытый интерес ~570 / 240 с × вес 1  =  140 весов/мин
--                                              -------------------
--                                              ~1610 весов/мин из 2400
--
-- Запросов при этом ~850 в минуту, то есть ~14 req/s — под потолком в 16.
-- Оговорка, которую надо назвать вслух: 16 req/s, если бы КАЖДЫЙ запрос был
-- стаканом, дали бы 4800 весов/мин и мы бы получили 429. Потолок в запросах
-- держит эту смесь, а не любую; настоящим решением был бы шлюз, считающий веса,
-- и это названо будущей работой, а не замазано числом. Пока страховкой служит
-- `VenueGate.Penalize` по 429.
--
-- Источник помечен 'documented': 2400/мин — число вендора, прочитанное из его же
-- ответа, а 16 req/s выведены из него нашей арифметикой выше. Это ровно тот
-- случай, что и WEEX в 0021 (2000 весов / 10 с → 200 req/s для веса 1), а не
-- 'assumed', как было записано, пока адаптера не было.
--
-- ---------------------------------------------------------------------------
-- 2. Такт стакана: 300 с, и это не осторожность, а арифметика
-- ---------------------------------------------------------------------------
-- Глобальное умолчание depth_interval_s = 60. На ~570 инструментах это
-- 570 × 5 = 2850 весов КАЖДУЮ МИНУТУ — 119 % всего, что Binance нам даёт, одним
-- датасетом. Оставить умолчание значило бы записать в базу такт, который
-- физически недостижим, и получать 429 ровно тогда, когда WS-фид упал и стакан
-- вернулся на REST, — то есть в самый неудачный момент. 300 с дают 570 весов в
-- минуту и разворачиваются за ~36 с при 16 req/s, так что такт выполним и с
-- живым сокетом, и без него.
--
-- Почему стакан на Binance по REST плох вдвойне: замерено сегодня, насколько
-- далеко от середины достаёт книга при разных limit —
--
--     limit=50  (вес 2)   BTC  0.7 bps   ETH  2.0 bps   DOGE   55 bps
--     limit=100 (вес 5)   BTC  1.4 bps   ETH  4.0 bps   DOGE  111 bps
--     limit=500 (вес 10)  BTC  7.3 bps   ETH 21.0 bps   DOGE  555 bps
--     limit=1000(вес 20)  BTC 17.2 bps   ETH 46.2 bps   DOGE 1112 bps
--
-- `DepthMath` обнуляет полосу, до края которой книга не дотянулась, поэтому по
-- BTC и ETH полосы 25 и 50 bps по REST пусты при ЛЮБОМ limit, а 10 bps по BTC —
-- только при limit=1000 ценой веса 20 на символ. Мы берём limit=100: он
-- закрывает все три полосы на всём, кроме BTC и ETH, а платить вчетверо ради
-- двух клеток на метрованном бюджете смысла нет. Настоящий ответ — сокет: он
-- ведёт книгу по всем уровням, которые публикует биржа, а не по окну из них.
--
-- ---------------------------------------------------------------------------
-- 3. ws_url и что именно уходит на сокет
-- ---------------------------------------------------------------------------
-- `wss://fstream.binance.com/public/stream` — МАРШРУТИЗИРОВАННЫЙ адрес. Binance
-- развёл публичный сокет на пути (/public, /market, /private), и это не косметика:
-- поток, запрошенный не на своём пути, отвечает HTTP 101 и молчит. Проверено
-- живьём и положено в репозиторий: `Fixtures/binance-ws/session-transcript.txt`
-- показывает, что SUBSCRIBE на чужом пути получает штатный ответ
-- `{"result":null}` — то есть УСПЕШНОЕ подтверждение — и после него ноль кадров
-- за 12 секунд, тогда как тот же поток на своём пути даёт 76 кадров за 8 секунд.
-- Ни рукопожатие, ни подтверждение подписки не отличают правильный путь от
-- неправильного; отличает только отсутствие кадров, поэтому у фида есть таймаут
-- живости на старте — единственный способ это заметить.
--
-- На сокет уходит ТОЛЬКО стакан. Снапшот сокет тоже умеет (@bookTicker,
-- !markPrice@arr, !ticker@arr), но эти три потока живут на ДВУХ разных
-- маршрутизированных путях и тикают по трём разным часам, и сведение их в одну
-- строку потребовало бы выбрать один received_at из трёх — ровно та форма
-- рассуждения, которая на разборе дала дефект «received_at = минимум батчевых
-- часов тихо теряет наблюдения». А снапшот по REST и не был дорогим: три
-- батчевых вызова, 55 весов на всю биржу. Дорогим был стакан, и он же —
-- единственное, что нельзя перезапросить потом ни за какие деньги.
--
-- ---------------------------------------------------------------------------
-- 4. Алиасы: активы с множителем в имени
-- ---------------------------------------------------------------------------
-- Тот же приём, что уже сеян в 0006 (1000PEPE) и 0011 (семь штук для WEEX):
-- контракт на 1000 единиц актива биржа называет «1000XXX», и без алиаса
-- авторегистрация создала бы канон «1000CAT» вместо «CAT» с множителем 1000.
-- Ниже — те из живого списка Binance, которых ещё нет.
--
-- Что СОЗНАТЕЛЬНО не заводится, и это важнее списка:
--
-- * `0G`, `1INCH`, `2Z`, `4`, `42` — начинаются с цифры, но это настоящие имена
--   активов, а не префиксы-множители. Названы здесь, чтобы следующий читатель
--   видел: их рассмотрели и решили, а не проглядели.
-- * `1000X`. По соглашению это был бы «X» с множителем 1000, но остаток — один
--   символ, и именно там разбор соглашения вероятнее всего принимает за префикс
--   часть настоящего имени. Независимого подтверждения нет (спота XUSDT у
--   Binance нет), а алиас — это утверждение о тождестве актива. Пусть лучше
--   канон останется «1000X» с множителем 1 — некрасиво, зато не выдумано.
-- * `LUNC` — единственный из списка, чьё существование подтверждено независимо
--   (спот LUNCUSDT есть). Остальные шесть опираются на соглашение вендора; это
--   сказано прямо, а не выдано за факт.
--
-- ---------------------------------------------------------------------------
-- 5. Что отвергнуто
-- ---------------------------------------------------------------------------
-- * Ставить `status = 'enabled'`. Соблазн велик: без этого миграция «включает»
--   площадку, которая не начнёт собирать. Но 0005 определил status как ЖЕЛАЕМОЕ
--   состояние, задаваемое человеком, и все три работающие сегодня площадки
--   включены руками, а не миграцией (0011 для WEEX тоже этого не делал). Право
--   решить, что четвёртая биржа начинает жечь бюджет и место, остаётся у
--   владельца. Значение 'planned' («адаптера нет») после этой миграции
--   становится неверным — и это ровно тот сигнал, который должен побудить
--   человека нажать кнопку.
-- * Заводить TRADIFI_PERPETUAL. Живой API отдаёт 191 такой контракт (XAUUSDT,
--   TSLAUSDT, NVDAUSDT) под значением, которого нет ни в одной доступной нам
--   документации. Это перпетуалы на акции и металлы; таблица активов здесь
--   построена под криптовалюты, и молча залить в неё TSLA было бы решением,
--   принятым списком исключений, а не человеком. Адаптер фильтрует
--   contractType БЕЛЫМ списком и сообщает о каждом незнакомом значении один раз
--   за процесс.
-- * Заполнять `transports_venue`. Binance предлагает по сокету заметно больше,
--   чем мы берём, но колонка пуста во ВСЕХ строках базы, и заполнить её для
--   одной клетки значило бы сделать матрицу неравномерно правдивой. Отдельная
--   работа, названная отдельной в плане.
-- * Понижать `snapshot` до WS. См. раздел 3.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Адреса площадки. charts_url остаётся пустым: в отличие от Kraken у Binance
-- свечи живут на том же хосте, что и остальной рынок.
-- ---------------------------------------------------------------------------
update segment
   set base_url = 'https://fapi.binance.com',
       ws_url   = 'wss://fstream.binance.com/public/stream'
 where code = 'binance-usdm';

do $$
begin
    if not exists (select 1 from segment
                    where code = 'binance-usdm' and base_url is not null and ws_url is not null) then
        raise exception 'binance-usdm остался без base_url или ws_url: адаптер не построится';
    end if;
end $$;

