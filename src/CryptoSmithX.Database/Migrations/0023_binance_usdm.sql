-- ---------------------------------------------------------------------------
-- Такт стакана. 60 с (умолчание) на ~570 инструментах — 2850 весов в минуту,
-- 119 % бюджета одним датасетом. См. раздел 2 заголовка.
-- ---------------------------------------------------------------------------
update segment_dataset
   set interval_s = 300
 where segment_code = 'binance-usdm' and dataset_code = 'depth';

do $$
begin
    if not exists (select 1 from segment_dataset
                    where segment_code = 'binance-usdm' and dataset_code = 'depth' and interval_s = 300) then
        raise exception 'у binance-usdm нет клетки depth: такт стакана некуда записать';
    end if;
end $$;

-- ---------------------------------------------------------------------------
-- Возможности площадки. Reconcile при старте объявит это сам из Capabilities
-- адаптера; строки ниже нужны, чтобы состояние базы было верным СРАЗУ после
-- миграции, до первого запуска Хаба, и чтобы переход попал в capability_log как
-- событие с датой, а не выглядел случившимся при ближайшем рестарте процесса.
-- ---------------------------------------------------------------------------
insert into capability_log (segment_code, dataset_code, capability_key, old_value, new_value, source, changed_by, note)
select 'binance-usdm', v.dataset, 'transports_us', c.value, v.transports, 'declared', '0023 migration',
       'У binance-usdm появился адаптер. Стакан идёт по WS (маршрутизированный /public/stream, '
       || 'локальная книга с REST-затравкой), остальное — батчевый REST.'
  from (values ('discovery', 'rest'), ('snapshot', 'rest'), ('depth', 'rest,ws'),
               ('candles', 'rest'), ('funding', 'rest')) as v(dataset, transports)
  join segment_dataset_capability c
    on c.segment_code = 'binance-usdm' and c.dataset_code = v.dataset and c.capability_key = 'transports_us'
 where c.value is distinct from v.transports;

update segment_dataset_capability c
   set value = v.transports, source = 'declared', valid_since = now(), filled_at = now(), filled_by = '0023 migration'
  from (values ('discovery', 'rest'), ('snapshot', 'rest'), ('depth', 'rest,ws'),
               ('candles', 'rest'), ('funding', 'rest')) as v(dataset, transports)
 where c.segment_code = 'binance-usdm' and c.dataset_code = v.dataset and c.capability_key = 'transports_us';

