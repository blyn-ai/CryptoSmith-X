-- ============================================================================
-- CryptoSmith X — миграция 0067: бюджет OKX — замер, а не заглушка.
--
-- Проход глубины OKX падал примерно каждый пятый раз на проде (14 из ~72 за
-- 6 часов, 2026-09-17), всегда одинаково: books-full отвечает 50011 «Rate limit
-- reached» на одном-двух символах из 35 (25 свопов + 10 спотов, один хост
-- www.okx.com, один гейт).
--
-- Замерено с отдельного IP 2026-09-17, books-full?sz=5000 без других запросов:
--
--     разом  5 / 8 / 10        отказов 0
--     разом 12 / 15 / 20       отказов 2 / 5 / 10
--     4 в секунду 10 с         0 из 40
--     5 в секунду 10 с         0 из 50
--     6 в секунду 10 с         10 из 60
--     8 в секунду 10 с         30 из 80
--
-- Потолок маршрута — 10 запросов за 2 секунды с IP.
--
-- Почему падало при 5 в секунду. Гейт — ведро на max_concurrent_requests (4)
-- жетонов с пополнением request_budget_per_s: в одно двухсекундное окно
-- помещается 4 + 2 × 5 = 14 запросов при потолке 10. Тот же проход, воспроизведённый
-- с того же IP с этими числами, упал 6 раз из 8, отказы только у books-full.
--
-- 3 в секунду при тех же 4 одновременных: 4 + 2 × 3 = 10 — ровно в потолок.
-- Постоянная потребность хоста около 1,5 в секунду (три ряда свечей по 25
-- свопам и 10 спотам в минуту плюс глубина раз в пять минут), так что запас
-- остаётся. Проход глубины на 35 символов займёт около 11 секунд при такте 300.
--
-- Гейт строится один раз на процесс — нужен перезапуск хаба, а он и так будет
-- при выкатке этой миграции.
-- ============================================================================

update exchange
   set request_budget_per_s    = 3,
       max_concurrent_requests = 4,
       request_budget_source   = 'measured',
       request_budget_note     = 'books-full: 10 запросов за 2 с с IP, замер 2026-09-17 (0067). '
                                 'Ведро 4 + 3/с даёт не больше 10 в двухсекундном окне.',
       request_budget_url      = 'https://www.okx.com/docs-v5/en/#order-book-trading-market-data-get-full-order-book'
 where code = 'okx';
