-- ============================================================================
-- CryptoSmith X — миграция 0043: studio_reader видит asset_alias, collector_status,
-- collector_run.
--
-- Сверка вижна UI (plans/csx-ui-plan.md) с тем, что реально лежит в PROD, потребовала
-- доски площадок (`/studio/`, полоса A1/A2) и реестра алиасов на карточке актива (A3).
-- Обе читают таблицы, которые 0025 назвала поимённо и сознательно НЕ выдала:
--
--   * asset_alias — «витрина показывает канон, который discovery уже записал в
--     base_asset; таблица написаний площадок ей не нужна» (0025, §«ещё не выдано»).
--     Это было верно, пока у витрины не было причины объяснять ПОЧЕМУ несколько
--     сырых символов сложились в один актив — A3 такую причину заводит.
--   * collector_status, collector_run — «витрина выводит свежесть из возраста самих
--     данных и окна вызова, а не из таблицы состояния сборщика» (та же секция).
--     Тоже верно для страницы актива, которая измеряет что видит сама. Полоса
--     площадок — новая страница другого вопроса: не «насколько свежи ЭТИ данные»,
--     а «как часто мы вообще звоним на эту площадку» — единственный источник для
--     этого встроенной мерой является collector_run, а не возраст строки.
--
-- Тот же приём, что 0042: гранты поимённые, не `grant select on all tables` — новое
-- видно читателю только по явному решению, а не автоматически.
-- ============================================================================

grant select on asset_alias to studio_reader;
grant select on collector_status to studio_reader;
grant select on collector_run to studio_reader;

comment on table asset_alias is
    'Сырое написание площадки (XBT, 1000PEPE) и множитель, которым discovery резолвит его в '
    'канонический actif. С 0043 читается доской площадок в studio (A3): карточка актива '
    'показывает, какие написания в него свернулись, а не только результат свёртки.';

comment on table collector_status is
    'Текущее состояние одного коллектора: last_attempt_at, last_success_at, '
    'consecutive_failures, avg_duration_ms, watermark_at. С 0043 читается полосой '
    'площадок в studio (A2) — раскрытие строки сегмента показывает состояние каждого '
    'датасета, а не только конфигурацию.';

comment on table collector_run is
    'Одна строка на каждый прогон коллектора. С 0043 читается полосой площадок в studio '
    '(A2, «последние проходы») — единственный источник, откуда видна РЕАЛЬНАЯ каденция '
    'опроса, а не заявленный interval_s.';
