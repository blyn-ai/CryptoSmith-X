-- ============================================================================
-- CryptoSmith X — миграция 0059: у market_price_candle появляется индекс по
-- received_at — тот самый, который 0013 дала market_candle по updated_at.
--
-- 0050 научила свёртку каскадировать mark/index-свечи. Её первый шаг, CTE
-- `touched`, ищет строки, переписанные с прошлого прохода: received_at >= @since.
-- Индекса по received_at не было, и это seq scan всего раздела. Замерено на
-- тесте 2026-09-13, EXPLAIN ANALYZE:
--
--     Parallel Seq Scan on market_price_candle_2026_09
--       Rows Removed by Filter: 523 999 (×3 воркера)   → найдено 408 строк
--       Buffers: read=22 236                            Execution Time: 6 054 ms
--
-- Каскад делает этот шаг на каждом таймфрейме, поэтому проход свёртки на тесте
-- длился 54 с при каденции 60 с — база была занята почти непрерывно, и запросы
-- студии упирались в таймаут: /studio/v2/BTC отдавала 500 через 65 с. На проде
-- тот же проход — 6–8 с, но строк там 5,9 млн против 1,6 млн на тесте, и расти
-- ему некуда, кроме как в ту же стену.
--
-- ПОЧЕМУ BRIN, как у 0013, а не btree. received_at пишется в момент вставки и
-- физически лежит почти по порядку; замерено pg_stats.correlation: 0,984 на
-- тесте, 0,999 на проде. BRIN на таких данных отсекает почти все страницы при
-- размере в килобайты и почти нулевой цене записи — а эта таблица пишется
-- непрерывно четырьмя свечными рядами на каждой площадке.
-- ============================================================================

create index market_price_candle_received_at_brin
    on market_price_candle using brin (received_at);
