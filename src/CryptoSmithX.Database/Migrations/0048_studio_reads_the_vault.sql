-- CryptoSmith X — миграция 0048: студия получает право читать два набора 0044.
--
-- 0044 завела vault_pair_state и vault_state, 0047 наполнила их живыми данными,
-- и всё это время публичная страница прочитать их НЕ МОГЛА: роль studio_reader
-- (0025) держит select на двадцати четырёх таблицах поимённо, и новых среди них
-- не было. Права не наследуются появлением таблицы — это и правильно: роль
-- публичного сайта должна перечислять то, что ей открыли, а не получать всё, что
-- кто-то создал.
--
-- ЗАЧЕМ ЧИТАТЬ. У рынка без книги входы функции импакта — это НЕ «дополнительные
-- данные», а замена глубины: onePercentDepthAbove/Below, ликвидность пула,
-- потолки OI и скос — ровно то, из чего у этого рынка складывается цена сделки.
-- План (§5) так и говорит: вместо карточки стакана у Avantis — скос OI и потолок
-- из набора. Пока страница говорила только о том, чего нет; теперь сможет
-- показать то, что есть.
--
-- Только select, как у всех остальных двадцати четырёх: публичная поверхность
-- ничего не пишет и не должна уметь.

grant select on vault_pair_state to studio_reader;
grant select on vault_state      to studio_reader;

comment on table vault_pair_state is
    'Наблюдение о ПАРЕ на vault-backed площадке: OI по сторонам в обеих единицах, '
    'потолки и ВХОДЫ функции ценового импакта. Отдельный набор, а не колонки '
    'общей строки: всё это NULL-по-модели для книжных площадок, то есть для '
    'целого класса венью. Входы, а не отсчёты при выбранных размерах. '
    'Читается студией с 0048 — у рынка без книги это её замена, а не довесок.';
