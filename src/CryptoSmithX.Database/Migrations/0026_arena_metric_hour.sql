-- ============================================================================
-- CryptoSmith X — миграция 0026: `market_metric_hour` витрине на чтение.
--
-- Одна строка грантов. Вся эта шапка — обоснование, потому что 0025 требует
-- ровно этого: там сознательно НЕ поставлен `alter default privileges`, и
-- сказано, зачем — «добавление таблицы к витрине это отдельная строка в
-- отдельной миграции, то есть решение, которое кто-то принял вслух». Вот оно,
-- вслух.
--
-- ----------------------------------------------------------------------------
-- Что именно было не так в 0025
-- ----------------------------------------------------------------------------
-- В списке «что ещё сознательно не выдано» стояло:
--
--     * `market_metric_hour` — агрегаты, которых страница пары не показывает.
--
-- Это не решение, которое стоит уважать. Это утверждение о странице, и оно
-- неверно. Правило 11 дизайн-системы (`src/web/ds-arena/readme.md`) называет
-- поимённо четыре колонки, которые несут часовую линию: спред, фандинг,
-- открытый интерес и глубина 25 bps. Это ровно те четыре величины, которые
-- лежат в `market_metric_hour` (0006: `spread_bps_avg`, `funding_rate_last`,
-- `open_interest_last`, `depth_bid_25bps_avg` / `depth_ask_25bps_avg`), и
-- больше нигде в схеме их часового среза нет.
--
-- Строка в 0025 писалась раньше, чем правило 11 было исправлено по отрисованной
-- странице (раздел Corrections в readme, 2026-09-06): до исправления правило
-- говорило «пять серий», после — семь, и три из них дала цена, а четыре вот эта
-- таблица. Формулировка не устарела по смыслу — она стала ложной по факту.
--
-- Все остальные пункты того же списка проверку страницей проходят, и ни один из
-- них эта миграция не трогает:
--
--   * `market_snapshot` — 26 млн строк, латераль по каждой паре. Отсутствие
--     гранта превращает требование blueprint («только `market_snapshot_latest`»)
--     в право доступа. Верно и сейчас.
--   * `webapp_user`, `capability_key`, `bot`, `bot_policy`, `tenant`,
--     `setting` — «не нужна» должно означать «не может». Верно и сейчас.
--   * `asset_alias` — витрина печатает канон. Верно.
--   * `funding_rate_history` — это другая страница. Верно, и заметьте разницу с
--     тем, что выдаётся здесь: история фандинга — строка на каждую выплату,
--     неограниченно; `market_metric_hour` — одна строка на инструмент-час.
--   * `collector_status`, `collector_run`, `collection_gap` — принцип, а не
--     объём: свежесть выводится из возраста самих данных и окна вызова, а не из
--     того, что сборщик написал про себя. Подмена одного другим и породила
--     инцидент с Kraken на 39 секундах. Верно, и этой миграцией не затронуто.
--
-- Из шести исключений ложно ровно одно, и оно здесь исправляется.
--
-- ----------------------------------------------------------------------------
-- Почему это дёшево, и почему `market_candle` — прецедент, а не контрпример
-- ----------------------------------------------------------------------------
-- `market_candle` витрине уже выдан (0025), и выдан ровно для того же: линия
-- цены под bid, ask и last читается из `market_candle.close`. Часовая свеча и
-- часовой срез микроструктуры — один и тот же гран, один и тот же паттерн
-- запроса (`where exchange_instrument_id = any(...) and <время> >= @from`,
-- ограничено списком инструментов одной пары и абсолютной границей окна,
-- вычисленной от времени ЗАПРОСА, не от `now()` в SQL). Свечей на инструмент в
-- сутки — 24 при часовом таймфрейме плюс все прочие таймфреймы, которые пишет
-- rollup; строк `market_metric_hour` — ровно 24. Выдать более крупную таблицу и
-- удержать меньшую — это не позиция по безопасности, это несогласованность.
--
-- Отдельно: `market_metric_hour` НЕ ротируется (0006), то есть это самая
-- долгоживущая таблица на публичной поверхности. Это учтено и это не меняет
-- ответа: запрос витрины ограничен и по инструментам, и по времени, страница
-- рисует двадцать пять часовых точек, а неограниченный забор истории одним
-- анонимным вызовом закрыт тем же, чем он закрыт для свечей — формой запроса,
-- лимитом соединений на роли и кэшем страницы, а не отсутствием гранта.
--
-- ----------------------------------------------------------------------------
-- Почему отдельный файл, а не правка 0025
-- ----------------------------------------------------------------------------
-- Мигратор применяет файл один раз и запоминает НОМЕР (`schema_version`),
-- контрольной суммы у него нет. На базе, где 0025 уже применена — а она уже
-- применялась при проверке предыдущих шагов, — правка её текста не выполнится
-- никогда и молча: роль осталась бы без гранта, а `schema_version` утверждала
-- бы, что всё на месте. Ровно тот отказ, который 0025 в своей же шапке
-- называет неприемлемым («Отказ, который видно, лучше записи, которая врёт»).
--
-- Строка в 0025 при этом поправлена — но только как ссылка сюда. Ложное
-- утверждение не должно остаться в файле, а решение должно лежать там, где оно
-- выполнится.
--
-- Отвергнуто:
--
--   * Оставить как есть и убрать у четырёх колонок место под линию. Это честнее
--     нынешнего (пустой зарезервированный слот — обещание, которого страница не
--     держит, и он неотличим от законно пустого слота у mark и index, у которых
--     второго измерения нет по правилу 11). Но это подгонка страницы под
--     опечатку в списке грантов: данные есть, они собраны, они дешёвые, и
--     единственная причина их не показывать — фраза, которая неверна.
--   * Считать серию на лету из `market_snapshot`. Это и есть тот запрос, ради
--     запрета которого `market_snapshot` не выдан, и он же — переписывание
--     `RollupJob` во вьюхе.
--   * Рисовать линию по тому, что уже на руках (интерполяция между двумя
--     снапшотами). Страница, единственный аргумент которой — «мы не показываем
--     того, чего не измеряли», выдумывает историю. То же самое, что напечатать
--     ноль там, где не было измерения, только читатель этого уже не проверит.
-- ============================================================================

grant select on market_metric_hour to arena_reader;
