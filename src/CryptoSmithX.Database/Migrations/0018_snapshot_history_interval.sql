-- 0018 — такт записи истории снапшотов становится настройкой (WP1).
--
-- Опрос идёт каждые 10 секунд, а в market_snapshot попадала одна строка в
-- минуту: пять наблюдений из шести жили секунды в market_snapshot_latest и
-- затирались следующим проходом. Спред, размеры у края стакана, открытый
-- интерес и глубина в тот момент — их нельзя перезапросить ни у одной биржи,
-- то есть выброшенные пять шестых не существуют больше нигде.
--
-- Такт был захардкожен константой в SnapshotCollector, хотя в этой системе вся
-- остальная конфигурация живёт в базе и правится из интерфейса: интервал
-- опроса, ретеншен, режим сбора. Теперь и он тоже.
--
-- Значение по умолчанию 60 намеренно: оно повторяет сегодняшнее поведение, то
-- есть миграция ничего не меняет сама по себе. Площадка с местом на диске
-- ставит 10 одной строкой и начинает хранить всё, что видит. Разница в объёме
-- шестикратная — 12.9 млн строк в сутки против 2.1 млн на 1488 инструментах, —
-- и это ровно тот выбор, который должен делать человек, глядя на свой диск, а
-- не программист, писавший коллектор год назад.
--
-- Ноль или отрицательное значение запрещены: они означали бы «писать историю
-- на каждом проходе», что и так выражается значением, равным интервалу опроса.
-- ============================================================================

insert into collection_setting (collection_code, key, value, kind, description) values
    ('snapshot', 'history_interval_s', '60', 'int',
     'Как часто наблюдение тикера попадает в market_snapshot, в секундах. Меньше или равно интервалу опроса '
     'означает «писать каждый проход». Значение больше интервала опроса означает, что часть наблюдений '
     'сохраняться не будет — они невосполнимы, поэтому решение осознанное.')
on conflict (collection_code, key) do nothing;
