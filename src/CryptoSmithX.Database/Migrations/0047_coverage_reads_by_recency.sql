-- CryptoSmith X — миграция 0047: coverage читается по СВЕЖЕСТИ, а индекс её
-- не знал.
--
-- Второй виновник той же медленной страницы, что чинила 0046, и найден тем же
-- способом — поочерёдным хронометражем запросов загрузчика. После того как
-- вакуум вернул историю снимков к сотне миллисекунд, наверх всплыл следующий:
-- выборка покрытия за сутки шла 1802 мс на 14 167 строках.
--
-- ПОЧЕМУ. Полоса 5 спрашивает у coverage ровно одно: «что из последних суток
-- тут есть» — то есть фильтрует по `range_to`. Единственный подходящий индекс,
-- coverage_lookup, устроен как (exchange_instrument_id, dataset_code,
-- range_from): по инструменту он попадает, а дальше `range_to` в нём НЕТ, и
-- Postgres вынужден поднять всё из кучи и отбросить половину уже там. В плане
-- это видно дословно: Bitmap Index Scan даёт 28 907 строк, «Rows Removed by
-- Filter: 14 737», 11 889 блоков кучи — ради 14 тысяч нужных.
--
-- Индекс по (instrument, range_to) превращает этот фильтр в условие поиска.
-- Замерено на тест-хосте, тот же запрос: 1802 мс → 25.9 мс, в 70 раз. Страница
-- при этом ушла с 8-12 с на 1.6-4.4 с.
--
-- ПОЧЕМУ ОТДЕЛЬНЫЙ, А НЕ ПЕРЕСТРОЕННЫЙ coverage_lookup. Тот обслуживает другой
-- вопрос — «что за история у этой клетки (инструмент, набор)», и range_from в
-- нём стоит третьим именно поэтому. Переставить его столбцы значило бы почи́нить
-- один запрос и сломать другой; таблица в полтора миллиона строк дешевле
-- второго индекса, чем одного медленного чтения на каждой загрузке страницы.
--
-- dataset_code в индекс НЕ включён намеренно: запрос группирует по нему, но не
-- фильтрует, а после сужения по инструменту и суткам остаётся горстка строк —
-- группировать её дешевле, чем носить лишнюю колонку в каждой записи индекса.

-- CONCURRENTLY нельзя: миграции идут в транзакции (см. Migrator). Таблица
-- пишется постоянно, но блокировка на построение индекса по полутора миллионам
-- строк — это секунды, и цена разовая.
create index if not exists coverage_recent
    on coverage (exchange_instrument_id, range_to);

comment on index coverage_recent is
    'Полоса 5 спрашивает покрытие ЗА ПОСЛЕДНИЕ СУТКИ, то есть фильтрует по '
    'range_to, которого нет в coverage_lookup — без этого индекса половина '
    'прочитанного отбрасывалась уже из кучи. Замерено: 1802 мс → 25.9 мс.';
