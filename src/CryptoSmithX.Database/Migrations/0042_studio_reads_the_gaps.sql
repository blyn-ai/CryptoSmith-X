-- ============================================================================
-- CryptoSmith X — миграция 0042: studio_reader видит collector_gap.
--
-- Полоса 5 второй страницы актива печатает пробелы сбора: где поток рвался,
-- почему и закрыт ли он до сих пор. Читает она их из collector_gap — таблицы,
-- которая существует с 0011 и переименована в 0019, и которой ни одна
-- миграция никогда не выдавала грант читателю.
--
-- Пока страницу не написали, это ничего не значило: до 7914967 в studio не
-- было ни одного запроса к этой таблице. С ним каждый /studio/v2/{asset}
-- падал на 42501 — permission denied for table collector_gap — потому что
-- чтение стоит ВНУТРИ кешируемой загрузки страницы, до первой отрисовки.
--
-- Гранты перечислены поимённо с 0025 и остаются такими: `grant select on all
-- tables` выдал бы читателю и то, что появится завтра, а смысл отдельной роли
-- ровно в том, что новое видно ей только по явному решению. Это оно.
--
-- Ролей две по историческим причинам (0027 переименовал arena_reader в
-- studio_reader, сохранив OID), поэтому грант один и на текущее имя.
-- ----------------------------------------------------------------------------

grant select on collector_gap to studio_reader;

comment on table collector_gap is
    'Интервал, в течение которого клетка не наблюдалась, с известной причиной. Отсутствие строки '
    'здесь напротив пропуска в данных означает причину, которой мы не знаем, — а не спокойный '
    'рынок. С 0042 читается не только операторскими запросами, но и полосой 5 страницы актива в '
    'studio: это единственное место в продукте, где пользователю видно, что поток рвался, поэтому '
    'cause и detail печатаются на странице дословно.';
