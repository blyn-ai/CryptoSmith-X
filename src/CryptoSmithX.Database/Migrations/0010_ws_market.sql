-- ============================================================================
-- CryptoSmith X — миграция 0010: WebSocket как основной источник живого рынка.
--
-- Решение владельца: WS — основной источник тикеров и стакана в реальном времени,
-- REST остаётся для bootstrap, метаданных, истории свечей/funding и восстановления.
-- REST-поллинг НЕ удаляется: это деградированный режим и кросс-чек. Контракт
-- адаптера и схема данных не меняются — меняется только, откуда адаптер Кракена
-- берёт живой срез. Поэтому здесь лишь конфигурация:
--
--   * exchange.ws_url — адрес публичного WS биржи. null = у биржи нет WS, адаптер
--     живёт чистым REST, как раньше. Сид для kraken-futures.
--   * три setting-а честности WS (kind=int), по стандарту репо — в базе, живые:
--       - ws_stale_after_s        — запись в кэше старше этого не отдаётся из WS
--         (замёрзший сокет не должен выглядеть свежим — received_at стареет, и
--         существующая staleness-логика видит проблему);
--       - ws_crosscheck_interval_s — как часто сверять WS-кэш с REST /tickers;
--       - ws_crosscheck_drift_bps  — расхождение mid-цены сверх этого помечает
--         книгу символа грязной и запускает ресинк (ловит тихо замёрзшую книгу
--         при живом сокете).
--
-- Что НЕ вошло и почему:
--   * Никаких новых таблиц данных — WS питает те же market_snapshot_latest и
--     depth-колонки через тот же SnapshotCollector; хранить WS-специфику негде и
--     незачем.
--   * WS-настройки на уровне символа — глобального порога достаточно; дробить
--     по инструменту усложнило бы без пользы.
-- ============================================================================

alter table exchange
    add column ws_url text;

update exchange set ws_url = 'wss://futures.kraken.com/ws/v1' where code = 'kraken-futures';

comment on column exchange.ws_url is
    'Публичный WebSocket биржи для живого рынка. null — биржа без WS, адаптер на чистом REST.';

insert into setting (key, value, kind, description) values
    ('ws_stale_after_s', '30', 'int',
     'WS: запись в кэше старше стольких секунд не отдаётся — замёрзший сокет не выглядит свежим.'),
    ('ws_crosscheck_interval_s', '60', 'int',
     'WS: как часто сверять кэш с REST /tickers (кросс-чек живости данных).'),
    ('ws_crosscheck_drift_bps', '50', 'int',
     'WS: расхождение mid-цены кэша и REST сверх стольких bps помечает книгу грязной и запускает ресинк.');
