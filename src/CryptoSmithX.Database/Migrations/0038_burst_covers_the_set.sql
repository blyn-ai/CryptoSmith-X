-- ============================================================================
-- CryptoSmith X — миграция 0038: burst должен накрывать собираемый список,
-- иначе проход растягивается на арифметику пополнения, а не на скорость биржи.
--
-- Требование владельца: обход площадки ≤ 500 мс. После 0036 (первые measured
-- бюджеты) и token bucket в VenueGate измерено на тесте за два часа:
--
--   площадка      собираем  burst  проход depth  проход candles
--   WEEX               25     32       0,65 с        1,02 с
--   Hyperliquid        25     32       0,68 с        1,13 с
--   Binance            44     32       1,53 с        1,96 с
--   Kraken            275     32       9,74 с       10,70 с
--
-- Закономерность одна: там, где инструментов МЕНЬШЕ burst, весь проход уходит
-- одним залпом и укладывается в доли секунды. Где больше — первые `burst`
-- запросов уходят сразу, остальные идут темпом пополнения:
--
--   Kraken: (275 − 32) / 32 = 7,6 с только на темп, плюс задержка сети.
--   Наблюдаемые 9,74 с — это ровно оно.
--
-- То есть 500 мс сегодня блокирует ОДНО число — max_concurrent_requests,
-- к которому VenueGate приравнивает burst (`_burst = maxConcurrentRequests`).
--
--
-- ----------------------------------------------------------------------------
-- A. Почему поднимается потолок CHECK, а не только значения
-- ----------------------------------------------------------------------------
-- Ограничение стоит с 0019: `max_concurrent_requests <= 64`. Оно было разумной
-- страховкой, пока никто не измерял; теперь измерено, и 64 меньше, чем один
-- собираемый список Kraken.
--
-- Замерено 2026-09-09 с тестового хоста, записано в plans/collection-policy.md §5.1–5.3:
--
--   * Kraken, 275 потоков ОДНИМ залпом, четыре раунда подряд без пауз:
--     все 275 → HTTP 200, p50 0,10 с, max 0,31–0,50 с, ноль отказов.
--   * Kraken, три пула по 64 = 192 одновременных: 768 запросов за ~4 с,
--     ноль отказов, потолок НЕ найден.
--
-- То есть 275 одновременных — не предположение, а воспроизведённое измерение.
-- Новый потолок 512, а не «сколько надо»: он должен пережить рост списка, но
-- остаться числом, за которым видно, что оно осознанное. Выше 512 —
-- отдельный разговор с новым замером.
--
-- ЧТО ЭТОТ ПОТОЛОК НЕ ЗНАЧИТ. Он не разрешает столько соединений всем: значение
-- ставится по площадкам ниже, и трём из четырёх оно не меняется вовсе.
--
--
-- ----------------------------------------------------------------------------
-- B. Kraken: 288 одновременных, 100 запросов в секунду
-- ----------------------------------------------------------------------------
-- 288 = 275 собираемых сегодня плюс запас на рост, чтобы первый же новый
-- контракт не вернул проход к пополнению.
--
-- rps 32 → 100, и это НЕ про скорость прохода: при burst ≥ списка весь проход
-- уходит залпом, темп на него не влияет вовсе. rps влияет на то, как быстро
-- корзина наполнится к СЛЕДУЮЩЕМУ проходу. У Kraken по одному гейту ходят
-- depth, candles, funding, snapshot и discovery; depth и candles идут примерно
-- раз в 70 с каждый и могут наложиться. При rps 32 корзина после залпа в 275
-- восстанавливается 8,6 с — второй коллектор в этом окне встал бы ждать. При
-- 100 — 2,75 с.
--
-- 100 ниже измеренных ~200 req/s, на которых отказов не было и потолок не
-- найден. Сеем ниже измерения намеренно: потолок не найден — значит неизвестно,
-- где он, и запас берётся в свою пользу.
--
--
-- ----------------------------------------------------------------------------
-- C. Binance: 64 одновременных, темп не трогаем
-- ----------------------------------------------------------------------------
-- 44 собираемых при burst 32 — это 32 сразу и 12 темпом. burst 64 накрывает
-- список целиком, и проход становится одним залпом.
--
-- rps остаётся 32. Бюджет Binance ВЕСОВОЙ: 2400 единиц веса в минуту, и вес
-- запроса от 1 (`openInterest`) до 40 (`ticker/24hr`). Наш ограничитель считает
-- запросы, а не вес, поэтому «40 rps» было бы правдой только для веса 1 и
-- съедало бы весь бюджет без остатка. 32 при списке в 44 и проходе раз в минуту
-- — это 0,7 запроса в секунду в среднем; пополнение не мешает ничему.
--
--
-- ----------------------------------------------------------------------------
-- D. WEEX и Hyperliquid — без изменений, и это решение, а не пропуск
-- ----------------------------------------------------------------------------
-- У обоих собирается по 25 инструментов при burst 32: список УЖЕ меньше залпа,
-- проходы 0,65 и 0,68 с. Поднимать нечего.
--
-- WEEX отдельно: его устойчивый потолок — 25 req/s на IP (измерено свободным
-- ходом 20 с: 500 успешных против 1712 отказов при большем темпе), а стена по
-- всплеску — около 500 запросов за 3 с с баном 6–8 с. Нынешние 30 rps держатся
-- ровно потому, что проход из 25 символов раз в минуту к стене не приближается.
-- Поднимать WEEX без нужды — это подойти к бану ради нуля выигрыша.
--
-- Hyperliquid: бюджет весовой (1200 веса в минуту, l2Book = 2, прочее в info =
-- 20). Посеянные 20 rps уже выше документированного и ниже измеренного — 0036
-- объясняет почему. 25 книг = 50 веса, запас двадцатикратный.
--
--
-- ----------------------------------------------------------------------------
-- E. Чего эта миграция НЕ чинит
-- ----------------------------------------------------------------------------
-- 1. 500 мс — свойство РАЗМЕРА СПИСКА, не кода. Пока список меньше burst, проход
--    укладывается. На полных списках: Kraken 275 (уже полный) останется, Binance
--    566 при весовом бюджете — около 14 с, WEEX 990 при 25 req/s на IP — около
--    40 с. Ни то, ни другое эта миграция не меняет и не может.
-- 2. Снапшот Kraken — 2,16 с при ОДНОМ bulk-запросе к бирже. Время уходит не в
--    сеть: SnapshotCollector пишет построчно, два `ExecuteAsync` внутри `foreach`
--    по тикерам, то есть 550 обращений к postgres на проход. При цели 500 мс
--    следующим узким местом становится наша собственная запись. Это код, не
--    схема, и здесь не чинится.
-- ============================================================================

alter table exchange drop constraint exchange_max_concurrent_requests_check;
alter table exchange add constraint exchange_max_concurrent_requests_check
    check (max_concurrent_requests >= 1 and max_concurrent_requests <= 512);

update exchange
   set max_concurrent_requests = 288,
       request_budget_per_s    = 100,
       request_budget_source   = 'measured',
       request_budget_note     = '0038: 275 одновременных воспроизведены живьём (p50 0,10 с, ноль отказов, '
                                 || 'потолок не найден); 288 = список плюс запас, 100 rps — на восстановление '
                                 || 'корзины между проходами, не на сам проход',
       updated_at              = now(),
       updated_by              = '0038 migration'
 where code = 'kraken';

update exchange
   set max_concurrent_requests = 64,
       request_budget_note     = '0038: burst накрывает 44 собираемых одним залпом. rps НЕ поднят: бюджет '
                                 || 'Binance весовой (2400/мин, вес запроса 1..40), а гейт считает запросы',
       updated_at              = now(),
       updated_by              = '0038 migration'
 where code = 'binance';

comment on column exchange.max_concurrent_requests is
    'Потолок одновременных запросов к площадке И РАЗМЕР ЗАЛПА: VenueGate приравнивает к нему burst '
    'token bucket. Если он меньше собираемого списка, проход растягивается на пополнение корзины, '
    'а не на скорость биржи — см. заголовок 0038. Верхняя граница 512 поднята с 64 там же.';
