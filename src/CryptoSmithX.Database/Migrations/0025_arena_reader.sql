-- ============================================================================
-- CryptoSmith X — миграция 0025: роль `arena_reader`, под которой ходит
-- публичная витрина. Только select, только по перечисленным таблицам.
--
-- ----------------------------------------------------------------------------
-- Почему отдельная роль вообще
-- ----------------------------------------------------------------------------
-- Arena — первая поверхность этого проекта, которую открывает кто угодно без
-- аутентификации. Всё, что было до неё, требовало входа (`/admin`) либо ключа
-- (`/api` ingest) либо вообще не слушало сеть (hub, migrator). Разница не в
-- количестве трафика, а в том, кто автор запроса: до сих пор это всегда был
-- человек, которого мы впустили.
--
-- Роль `marketdata` — владелец схемы. Ей можно insert, update, delete, drop
-- table, truncate — она этим и занимается: миграции, discovery, сбор. Дать
-- публичному процессу эту учётку значит поставить между анонимным HTTP-запросом
-- и `drop table market_snapshot` ровно один слой — наш собственный код запросов.
-- Один слой — это не защита, это надежда. Ошибка склейки строки в одном из пяти
-- запросов витрины (а их будет писать другой агент, в другом шаге, по параметрам
-- из URL) в худшем случае должна кончаться ошибкой прав, а не потерей 26 млн
-- строк снапшотов.
--
-- Поэтому: `arena_reader`, login, select и больше ничего. Даже если запрос
-- витрины окажется дырявым, postgres откажет раньше, чем что-либо изменится.
--
-- Отвергнуто:
--
--   * Ходить под `marketdata` и «просто писать аккуратные запросы». См. выше:
--     это не механизм, это обещание.
--   * `set role arena_reader` в строке подключения (`Options=-c role=...`) под
--     учёткой `marketdata`. Сессия при этом остаётся аутентифицированной как
--     владелец схемы, и одного `reset role` — который умещается в ту же дыру,
--     от которой мы защищаемся, — достаточно, чтобы вернуть все права. Роль,
--     которую можно снять, не является границей.
--   * Реплика только на чтение. Обсуждалась в `arena-public-site.md`; отдельная
--     машина под витрину не нужна, пока витрина живёт на том же хосте, что и
--     база (это записанное решение), а от записи защищает роль, а не топология.
--   * Читать через `MarketData.Api`. `/v1` — контракт для машин, его форма не
--     должна ползти под нужды одной страницы. Решено в blueprint.
--
-- ----------------------------------------------------------------------------
-- Почему таблицы перечислены поимённо, а не `grant select on all tables`
-- ----------------------------------------------------------------------------
-- `on all tables in schema public` выдало бы витрине заодно `webapp_user`
-- (логины и хеши паролей администраторов), `capability_key` (ключи площадок),
-- `bot`, `bot_policy`, `tenant`, `setting`. Публичной странице не нужна ни одна
-- из них, и «не нужна» должно означать «не может», а не «не запрашивает».
--
-- `alter default privileges` тоже не ставится намеренно. С ним каждая следующая
-- миграция молча расширяла бы публичную поверхность: завели таблицу — она уже
-- видна анониму, и никто об этом не подумал. Без него добавление таблицы к
-- витрине — это отдельная строка в отдельной миграции, то есть решение, которое
-- кто-то принял вслух.
--
-- Отдельно про `market_snapshot`. Его в списке НЕТ, и это не забывчивость.
-- Blueprint требует, чтобы все пять запросов витрины читали
-- `market_snapshot_latest`, а не латераль по истории, как это делает
-- `PairStore` в админке: на 26 млн строк латераль по каждой паре — это тот
-- запрос, которым публичную страницу кладут одним curl в цикле. Отсутствие
-- гранта превращает это требование из соглашения в право доступа: запрос к
-- истории не «медленно работает на проде», он не компилируется на первом же
-- прогоне у автора.
--
-- Что ещё сознательно не выдано:
--
--   * `asset_alias` — витрина показывает канон, который discovery уже записал в
--     `base_asset`; таблица написаний площадок ей не нужна.
--   * `funding_rate_history` — ставка фандинга и её интервал лежат в строке
--     `market_snapshot_latest`, страница печатает их оттуда. История фандинга —
--     это другая страница, и когда она появится, грант будет отдельной строкой.
--   * `collector_status`, `collector_run`, `collection_gap` — здоровье сбора.
--     Витрина выводит свежесть из возраста самих данных и окна вызова (§4
--     blueprint), а не из таблицы состояния сборщика. Это принципиально: именно
--     подмена «данные старые» на «сборщик что-то про себя написал» и породила
--     инцидент с Kraken на 39 секундах.
--   * `market_metric_hour` — агрегаты, которых страница пары не показывает.
--     ОТМЕНЕНО МИГРАЦИЕЙ 0026. Утверждение неверно: правило 11 дизайн-системы
--     называет спред, фандинг, открытый интерес и глубину 25 bps колонками с
--     часовой линией, а часовой срез этих четырёх величин лежит здесь и больше
--     нигде. Строка написана раньше, чем правило 11 было исправлено по
--     отрисованной странице. Грант — в 0026, вместе с разбором; отдельным
--     файлом, потому что мигратор применяет по номеру и правка этого файла на
--     уже мигрированной базе не выполнилась бы никогда и молча.
--
-- Выданы, наоборот, `dataset` и `segment_dataset`: из их каскада
-- (`segment_dataset.interval_s → dataset.default_interval_s`) выводятся окна
-- свежести на инструмент. Без них витрина вернулась бы к плоским 30 секундам,
-- то есть к тому самому багу второй раз.
--
-- `schema_version` выдана потому, что Arena, как api и webapp, вызывает
-- `Migrator.VerifyAsync` на старте и обязана громко отказаться подниматься на
-- отставшей схеме.
--
-- ----------------------------------------------------------------------------
-- Про пароль. Читать целиком, прежде чем катить это на хост, видимый из сети
-- ----------------------------------------------------------------------------
-- Пароль выставляется ТОЛЬКО в момент создания роли и только если роли ещё нет.
-- Значение — `arena_reader`, то есть известное всем, кто видел репозиторий.
--
-- Это ровно тот же приём, что уже стоит в `deploy/docker-compose.yml`:
-- `POSTGRES_PASSWORD: ${POSTGRES_PASSWORD:-marketdata}`. Локальная сборка
-- поднимается из чистого клона одной командой, а на реальной площадке значение
-- приходит из `/opt/cryptosmithx/.env` (chmod 600), которого в git нет.
--
-- Условие `if not exists` здесь несёт весь вес: на площадке, где оператор уже
-- завёл `arena_reader` со своим паролем — а на VM клиента он это сделать
-- ОБЯЗАН, см. §1, там владелец схемы не имеет права создавать роли, — миграция
-- пароль НЕ трогает, она только выдаёт гранты. Обратный порядок (сначала
-- миграция, потом `alter role arena_reader password`) работает так же: миграция
-- применяется один раз, второй раз create не выполнится, и ротация переживёт
-- любой следующий деплой.
--
-- Почему известный пароль здесь терпим, а для `marketdata` был бы нет: этой
-- учётке доступны ровно те строки, которые витрина и так отдаёт анониму по
-- HTTP. Утечка пароля даёт злоумышленнику то, что он может получить, открыв
-- сайт. Ни `webapp_user`, ни `capability_key`, ни права на запись за ним нет —
-- см. список выше. Плюс postgres в обеих конфигурациях слушает только loopback
-- и шлюз докера (`listen_addresses` в `provision-host.sh`, `127.0.0.1:` в
-- compose), так что дотянуться до порта из сети всё равно неоткуда.
--
-- Всё равно ротируйте на площадке. «Терпим» — это не «правильно».
--
-- ----------------------------------------------------------------------------
-- Что придётся сделать руками на VM клиента, и почему это не спрятано
-- ----------------------------------------------------------------------------
-- Там владелец схемы не имеет CREATEROLE, поэтому первый же прогон этой миграции
-- на той машине остановится с текстом ошибки ниже: одна команда psql
-- суперпользователем плюс одна строка в /opt/cryptosmithx/.env, после чего
-- деплой повторяется и проходит. Деплой на VM запускается человеком вручную
-- (workflow_dispatch), мигратор падает раньше, чем что-либо пересоздаётся, и
-- работающий стек остаётся работать на старых образах.
--
-- Альтернатива — тихо пропустить create и гранты, чтобы миграция «прошла» — была
-- отвергнута, и по причине более неприятной, чем неудобство: миграции
-- применяются один раз. Роль, заведённая оператором на следующий день, осталась
-- бы навсегда без грантов, а `schema_version` утверждала бы, что 0025 применена.
-- Отказ, который видно, лучше записи, которая врёт.
--
-- ----------------------------------------------------------------------------
-- Лимит соединений
-- ----------------------------------------------------------------------------
-- `connection limit 30` на роли и `Maximum Pool Size=20` в строке подключения
-- Arena — пара, работающая вместе. Названный в `arena-public-site.md` риск
-- публичной поверхности — исчерпание пула соединений анонимным трафиком; без
-- лимита это исчерпание общего пула postgres, то есть админка и hub ложатся
-- вместе с витриной. С лимитом витрина упирается в свой потолок и деградирует
-- одна. Потолок роли выше потолка пула намеренно: разница — это запас на
-- psql-сессию человека, который придёт разбираться, почему витрина упёрлась.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. Роль
-- ----------------------------------------------------------------------------
-- Все `no*` — это и так значения по умолчанию. Написаны явно, потому что это
-- перечень того, чего публичной поверхности нельзя, и он должен читаться в
-- файле, а не подразумеваться из документации postgres.
--
-- `create role` требует прав, которых у владельца схемы может не быть, и это не
-- теория: в контейнерной сборке `marketdata` создан образом postgres как
-- суперпользователь и create отработает, а на VM клиента его завёл
-- `provision-host.sh` строкой `create role marketdata login` — без CREATEROLE.
-- Там миграция создать роль не сможет, и это правильно: владелец схемы не
-- должен уметь заводить роли, иначе граница, которую мы здесь строим, снимается
-- изнутри.
--
-- Поэтому отказ ловится и переписывается в осмысленный: одна команда для
-- оператора вместо `permission denied to create role` посреди прогона миграций.
-- Молча пропустить create нельзя — гранты ниже упадут на несуществующей роли, и
-- отказ всё равно случится, только на десять строк позже и без объяснения.
do $$
begin
    if not exists (select 1 from pg_roles where rolname = 'arena_reader') then
        begin
            create role arena_reader
                login password 'arena_reader'
                nosuperuser nocreatedb nocreaterole noreplication nobypassrls
                connection limit 30;
        exception when insufficient_privilege then
            raise exception
                'роли arena_reader нет, а у % нет прав её создать', current_user
                using hint =
                    'один раз суперпользователем: sudo -u postgres psql -d marketdata -c "create role '
                    'arena_reader login password ''<сгенерированный>'' nosuperuser nocreatedb '
                    'nocreaterole noreplication nobypassrls connection limit 30;" — затем строкой в '
                    '/opt/cryptosmithx/.env: ARENA_DATABASE_CONNECTION_STRING=Host=<шлюз>;Port=5432;'
                    'Database=marketdata;Username=arena_reader;Password=<тот же>;Maximum Pool Size=20 '
                    '— и повторить деплой.';
        end;
    end if;
end $$;


-- ----------------------------------------------------------------------------
-- 2. Доступ в схему
-- ----------------------------------------------------------------------------
-- usage — «видеть объекты», не «создавать». Право create в схеме public в
-- postgres 15+ у PUBLIC отобрано по умолчанию, и мы его не возвращаем: роли
-- витрины незачем заводить объекты. Ничего не revoke'аем сверх этого — отбирать
-- у PUBLIC то, чего у него уже нет, значит писать строку, которую следующий
-- читатель примет за существующую угрозу.
grant usage on schema public to arena_reader;


-- ----------------------------------------------------------------------------
-- 3. Гранты. Ровно то, что читает витрина
-- ----------------------------------------------------------------------------
-- Схема, на которой отказываемся подниматься, если она отстала.
grant select on schema_version to arena_reader;

-- Каталог: биржа → сегмент → набор данных. Из последних двух выводится окно
-- свежести на инструмент (каскад interval_s), из первых двух — как называется
-- площадка в строке сравнения.
grant select on exchange           to arena_reader;
grant select on segment            to arena_reader;
grant select on dataset            to arena_reader;
grant select on segment_dataset    to arena_reader;

-- Инструменты и то, во что сворачивается пара в заголовке.
grant select on exchange_instrument  to arena_reader;
grant select on asset                to arena_reader;
grant select on asset_family         to arena_reader;
grant select on asset_family_member  to arena_reader;

-- Рынок. Именно latest, а не история — обоснование в шапке.
grant select on market_snapshot_latest to arena_reader;
grant select on market_candle          to arena_reader;
