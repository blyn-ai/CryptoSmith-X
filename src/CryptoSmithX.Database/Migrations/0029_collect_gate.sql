-- ----------------------------------------------------------------------------
-- 4. Индекс под очередь NEW
-- ----------------------------------------------------------------------------
-- Ставится вместе со своим читателем, как 0024 поставил exchange_instrument_pair
-- вместе с запросами витрины. Читателей ровно два, и оба на одной странице
-- админки: фильтр «collect = new» в списке инструментов и счётчик очереди в
-- шапке той же страницы, который считается на КАЖДЫЙ её рендер. Оба спрашивают
-- ровно предикат ниже (InstrumentStore.UndecidedSql).
--
-- Частичный, а не полный по (collect, collect_changed_at). Предикат отбирает
-- горстку строк из таблицы, которая растёт: очередь — это то, что приехало и
-- ещё не разобрано, то есть по построению малая величина, и индекс под неё
-- размером с эту горстку, а не с таблицу. Тот же приём, что у 0024:
-- `... where collect`.
--
-- Честно про размер выигрыша СЕГОДНЯ: на тестовой базе 2258 строк, из них под
-- предикат подпадает 0, и seq scan там занимает доли миллисекунды — измеримой
-- разницы нет. Индекс покупается не под сегодняшний объём, а под форму запроса:
-- «покажи очередь» должно стоить размер очереди, а не размер таблицы, иначе
-- цена страницы растёт вместе с книгой инструментов, которая только растёт.
--
-- Колонки в индексе — те, по которым список сортируется по умолчанию
-- (segment_code, exchange_symbol): тогда и отбор, и порядок берутся из индекса,
-- а сама очередь читается без сортировки.
create index exchange_instrument_undecided
    on exchange_instrument (segment_code, exchange_symbol)
    where collect = false and collect_changed_at is null;

comment on index exchange_instrument_undecided is
    'Очередь NEW: инструменты, про которые никто не решал. Предикат повторяет '
    'InstrumentStore.UndecidedSql; менять их надо вместе.';
