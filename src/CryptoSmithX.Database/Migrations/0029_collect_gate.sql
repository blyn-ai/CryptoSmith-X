-- ============================================================================
-- CryptoSmith X — миграция 0029: новый инструмент приходит ВЫКЛЮЧЕННЫМ, а у
-- списка автоодобренных базовых активов появляется место, которое правит админ.
--
-- Схема меняется в трёх местах:
--   * exchange_instrument.collect получает default false вместо true (0008:31);
--   * asset получает колонку auto_collect (boolean not null default false),
--     засеянную true для 25 активов;
--   * появляется частичный индекс под очередь NEW (п. 4) — вместе со своим
--     читателем, экраном очереди в админке, а не «на будущее».
--
-- Ни одной существующей строки exchange_instrument эта миграция не касается.
-- Это сказано не для порядка слов. Разовая уборка — 1864 инструмента вне списка
-- выключены, каждому проставлены collect_changed_at, collect_changed_by и
-- collect_note, — уже сделана руками по решению владельца, и её здесь нет
-- намеренно. Решение о данных не место в истории схемы: тот, кто накатит 0029
-- на другую базу, должен получить новое ПРАВИЛО, а не чужие 1864 решения,
-- принятые в другой день про другой набор строк. Поэтому в файле нет ни одного
-- UPDATE по инструментам.
--
--
-- ----------------------------------------------------------------------------
-- A. Почему дефолт переворачивается
-- ----------------------------------------------------------------------------
-- Сегодня новый листинг попадает в сбор молча. DiscoveryCollector.cs:92-125 не
-- упоминает collect ВООБЩЕ: колонки нет ни в списке вставки, ни в `do update
-- set`. Отсюда два разных факта, и в этой правке важны оба:
--
--   * новая строка берёт ДЕФОЛТ КОЛОНКИ — то есть до сих пор true. Площадка
--     завела ночью новый вечный контракт — следующим проходом discovery мы уже
--     льём по нему снапшоты, свечи, глубину и фандинг, никого не спросив;
--   * существующая строка сохраняет то, что поставил оператор — discovery её
--     не переписывает. Эта половина ПРАВИЛЬНАЯ и обязана пережить правку. Она
--     её и переживает: `alter column ... set default` задаёт значение для
--     БУДУЩИХ вставок и не трогает ни одной существующей строки. После этой
--     миграции всё, что сейчас собирается, собирается дальше — включая 280
--     инструментов kraken-futures, оставленных включёнными по прямому указанию,
--     и 20 инструментов `fake`.
--
-- Дальше — измерения, а не ощущения. Тестовая база, 2258 инструментов, замер
-- сделан через 34 минуты после прохода discovery:
--
--   * дату листинга сообщают только две площадки. binance-usdm — 697 строк с
--     listed_at, из них 4.4% моложе полугода и 19.8% моложе года;
--     kraken-futures — 280 строк, 6.8% и 16.1%. Абсолютом по всей таблице: 50
--     инструментов моложе полугода (binance-usdm 31, kraken-futures 19);
--   * hyperliquid (233) и weex-futures (1028) не сообщают дату листинга НИ ПО
--     ОДНОЙ строке: listed_at там null везде. Доля свежих листингов для них —
--     прочерк, а не ноль. Она не измерена, потому что измерять нечем;
--   * first_seen_at как мера притока сейчас бесполезен: самая старая строка в
--     таблице увидена 2026-08-31, база младше недели, и «увиден позже первого
--     прохода» у binance-usdm читается как 697 из 697 — это дата включения
--     сегмента, а не приток листингов.
--
-- Оценку «28–41% книги каждой живой площадки моложе полугода» воспроизвести не
-- удалось: ни в одном окне (6, 12, 24 месяца) ни у одной площадки доля в этот
-- коридор не попала (binance-usdm 4.4 / 19.8 / 54.7, kraken-futures 6.8 / 16.1 /
-- 45.7). В шапку миграции она поэтому не ставится: цифра без измерения — это
-- прочерк, чужая она или своя.
--
-- Аргумент от этого не рушится, потому что он не про долю. Полсотни листингов
-- за полгода на двух площадках — это полсотни решений, которых никто не
-- принимал; плюс 1261 строка, про свежесть которой мы не знаем ничего. Ворота
-- нужны ровно потому, что приток нельзя ни увидеть, ни проаудировать: у
-- половины книги нет даже даты, по которой его можно было бы посчитать задним
-- числом.
--
-- ЧТО ЭТО НЕ ДЕЛАЕТ. Не выключает ничего из включённого. Не мешает discovery
-- видеть и обновлять инструмент: 0008 уже сказал, что collect гасит сбор, а не
-- наблюдение, и это не меняется — у выключенного инструмента по-прежнему
-- обновляются status, last_seen_at и raw_json, иначе мы бы не заметили его
-- делистинг. Не трогает четыре сборщика: SnapshotCollector.cs:20,
-- DepthCollector.cs:38, CandleCollector.cs:37, FundingCollector.cs:35 читают
-- `collect = true` каждым проходом, так что правило начинает действовать без
-- рестарта — и точно так же без рестарта подействует решение админа.
--
-- ОТВЕРГНУТО: научить DiscoveryCollector писать `collect = false` в списке
-- вставки вместо смены дефолта. Дефолт — одно место и действует на ЛЮБОГО
-- писателя, включая руки в psql и будущую вторую точку вставки. Колонка же в
-- списке вставки живёт в трёх строках от `do update set`, и добавить её туда
-- следующей правкой — на один невнимательный день работы: тогда каждый проход
-- discovery затирал бы решение оператора обратно в false. Дефолт физически не
-- может этого сделать.
--
--
-- ----------------------------------------------------------------------------
-- Состояние «NEW» выводится, а не хранится
-- ----------------------------------------------------------------------------
-- Инструмент, про который никто не решал, — это ровно
--
--     collect = false and collect_changed_at is null
--
-- Инструмент, который выключил человек, несёт отметку времени и почти всегда
-- заметку, потому что InstrumentStore.SaveCollectAsync (:212) пишет все четыре
-- поля одним оператором и не умеет писать collect без collect_changed_at.
-- Другого писателя у этих колонок нет.
--
-- Проверено на тестовой базе, а не выведено: строк, читающихся как NEW, сейчас
-- НОЛЬ. Разбивка по (сегмент, collect, есть ли отметка, есть ли заметка):
-- binance-usdm 653 f/t/t и 44 t/f/f, hyperliquid 208 f/t/t и 25 t/f/f,
-- weex-futures 1003 f/t/t и 25 t/f/f, kraken-futures 280 t/f/f, fake 20 t/f/f.
-- То есть все 1864 выключенных руками несут и время, и заметку — и НЕ читаются
-- как NEW, чего и добивались. Первым NEW станет первый листинг, приехавший
-- после этой миграции.
--
-- ОТВЕРГНУТА отдельная колонка состояния (collect_state / status enum
-- new|approved|rejected). Она была бы вторым источником той же правды: тумблер
-- в админке пишет collect, а колонка состояния — то же самое другими словами, и
-- разъезжаются они молча, при первом же UPDATE в обход UI. Держать их в
-- согласии может либо триггер (в этой базе триггеров нет по соглашению 0001),
-- либо дисциплина в коде — то есть ничего. Вдобавок такая колонка потребовала
-- бы бэкфилла: чем заполнить её у 2258 существующих строк, каждая из которых
-- уже несёт ответ в collect/collect_changed_at? Это было бы то самое решение о
-- данных, которому в миграции не место. Выводимая форма не требует ни бэкфилла,
-- ни синхронизации: она читает те же колонки, которыми решение и принимается.
--
--
-- ----------------------------------------------------------------------------
-- B. Где живёт список автоодобрения
-- ----------------------------------------------------------------------------
-- Список назван в базовых активах — «BTC, ETH, SOL...», — и `asset` это ровно
-- справочник БАЗОВЫХ активов (0006:45-50; FK exchange_instrument.base_asset ->
-- asset.code). Признак ставится на ту же строку, к которой относится:
-- auto_collect boolean not null default false. Админка правит его тем же
-- экраном Assets, которым уже правит имя и заметку канона, и той же парой
-- updated_at/updated_by из 0008 — заводить третью пару аудита для соседней
-- колонки той же строки было бы удвоением без выгоды.
--
-- Признак должен существовать ДО того, как листинг приедет: смысл его в том,
-- чтобы новый BTC-контракт не ждал человека. Поэтому сид заводит все 25 строк
-- независимо от того, видела ли их площадка, — строка `asset` без листингов
-- безвредна (FK смотрит из инструмента в актив, не наоборот).
--
-- ОТВЕРГНУТО, по порядку:
--
--   * Отдельная таблица (auto_collect_asset: code, note, created_at/by).
--     Строго говоря, работает. Но это таблица из одной значащей колонки,
--     ключуемая тем же кодом актива, что и `asset`, и без FK на него (FK
--     сломал бы возможность внести в список актив, которого ещё нет ни на одной
--     площадке — а это половина смысла списка). Получается второй реестр
--     активов рядом с первым: два места, где живёт код 'BTC', две страницы в
--     админке, и вопрос «почему BTC есть здесь и нет там» без ответа. Признак
--     на существующей строке отвечает на него тем, что вопроса не возникает.
--
--   * Ключ в setting (0007) со списком через запятую. Это худший вариант из
--     трёх и по конкретной причине: строка 'BTC,ETH,SOL,...' не имеет ни FK, ни
--     уникальности, ни регистра, ни защиты от пробела после запятой. Опечатка
--     'BCT' не отличима от актива, которого мы просто пока не видели, и молча
--     ничего не одобряет. setting задуман под скалярные значения (интервалы,
--     флаги) с подсказкой типа для валидации в UI, и список сущностей,
--     существующих в базе своими строками, — не скаляр. Правка списка из 25
--     позиций через одно текстовое поле — это ещё и запись всего списка целиком
--     ради одной галочки.
--
--   * asset_family из 0024. Это ДРУГАЯ ОСЬ, и 0024 говорит это прямым текстом:
--     семейство построено под КОТИРОВКУ (USD/USDT/USDC сворачиваются в одну
--     пару показа), а активов-котировок в `asset` нет и не будет — discovery
--     регистрирует только базовые каноны (DiscoveryCollector.cs:83), и
--     `select count(*) from asset where code in ('USD','USDT','USDC')` даёт
--     ноль. У asset_family_member первичный ключ — asset_code, то есть актив
--     входит РОВНО в одно семейство: втащив туда «семейство AUTO-COLLECT», мы
--     бы сделали членство в списке автоодобрения взаимоисключающим со всяким
--     будущим настоящим семейством (WBTC->BTC), которое 0024 явно оставил на
--     будущее. Одобрение сбора и свёртка показа — разные вопросы к одному
--     активу, и одна колонка-ключ на два вопроса не отвечает.
--
-- Отдельно отвергнуто: exchange.blacklist / exchange.quote_assets (0007) как
-- место для списка. Они настраивают ОДНУ площадку и работают по символам
-- площадки; список автоодобрения — межплощадочный и говорит про актив.
--
--
-- ----------------------------------------------------------------------------
-- Чего в этой миграции НЕТ и почему
-- ----------------------------------------------------------------------------
--   * Кода, который читает auto_collect. Это надо сказать вслух: сама по себе
--     схема обход ворот НЕ включает. Пока DiscoveryCollector не научится
--     вставлять `collect = true` для базовых активов с auto_collect, после этой
--     миграции ВСЁ новое приезжает выключенным, включая BTC. Это следующий шаг,
--     и он в коде, а не здесь. Заметный побочный эффект: на чистой базе
--     (dev/CI) после включения этого шага `fake` наберёт 15 инструментов из 20
--     — APT, ATOM, INJ, OP и TIA в список не входят.
--   * (Было — «индекса под очередь NEW здесь нет». Теперь есть, п. 4: экран,
--     который по нему ходит, приехал тем же неотгруженным изменением, и условие
--     «ставить вместе с читателем» выполнено, а не отменено. Читатель — фильтр
--     collect=new и счётчик очереди на /Admin/Instruments,
--     InstrumentStore.UndecidedSql.)
--   * Автоодобрения на уровне пары или площадки (BTC — да, но только на
--     binance). Список назван активами, потому что решение принималось про
--     активы; сузить его потом можно, расширить обратно — нет.
--   * Снятия default с collect совсем (`drop default`, чтобы вставка без
--     колонки падала). Упало бы discovery целиком, одной транзакцией на весь
--     проход, — ровно тот отказ, который воспроизведён и описан в 0024.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. Ворота: новое приезжает выключенным
-- ----------------------------------------------------------------------------
alter table exchange_instrument
    alter column collect set default false;

comment on column exchange_instrument.collect is
    'НАШЕ решение: собирать ли по инструменту снапшоты/свечи/глубину/фандинг. '
    'Не путать со status — тот наблюдаемый (что говорит биржа). discovery видит и '
    'обновляет инструмент независимо от collect; выключается только сбор данных. '
    'С 0029 дефолт = false: новый листинг приезжает и ждёт решения, а не собирается молча. '
    'discovery колонку не пишет вовсе, поэтому решение оператора переживает любой проход.';

comment on column exchange_instrument.collect_changed_at is
    'Когда collect в последний раз меняли через UI. Вместе с collect образует состояние '
    '«про инструмент никто не решал»: collect = false and collect_changed_at is null. '
    'Отдельной колонки состояния нет намеренно — она была бы вторым источником той же правды.';


-- ----------------------------------------------------------------------------
-- 2. Автоодобрение — признак на каноническом активе
-- ----------------------------------------------------------------------------
alter table asset
    add column auto_collect boolean not null default false;

comment on column asset.auto_collect is
    'Проходит ли новый листинг этого базового актива ворота сам, без решения человека. '
    'Правится в админке (аудит — updated_at/updated_by, как у имени и заметки). '
    'Дефолт false: неизвестный актив, зарегистрированный discovery автоматически, '
    'автоодобрения не получает. На уже существующие exchange_instrument.collect не влияет — '
    'признак читается только в момент появления НОВОГО листинга.';


