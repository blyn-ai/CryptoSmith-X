-- ============================================================================
-- CryptoSmith X — миграция 0049: порог вакуума по вставкам взят из замера,
-- и функция перестаёт затирать настройку при каждом вызове.
--
-- Две поправки к 0046, обе найдены попыткой ПРОВЕРИТЬ её на живом хосте.
--
--
-- 1. ЦИФРА БЫЛА ВЕЛИКА ВТРОЕ С ЛИШНИМ
--
-- 0046 поставила 200 000 «примерно сутки на ~420 инструментах». Замер этого не
-- подтвердил. После ручного вакуума партиция снимков отвечала за 11.5 мс; через
-- 27 437 вставок тот же запрос шёл уже 810 мс, то есть деградация наступает
-- за десятки минут, а не за сутки. Порог, до которого набирается 200 000, всё
-- это время держал бы страницу медленной — вакуум приходил бы уже к разобранной
-- карте видимости.
--
-- 20 000: при наблюдаемых ~40 000 вставок в час это вакуум примерно раз в
-- полчаса. Он дёшев ИМЕННО НА ТАКОЙ ТАБЛИЦЕ и это не предположение, а устройство
-- механизма: вакуум по вставкам обходит только страницы, ещё не отмеченные
-- all-visible, а в append-таблице это ровно дописанный хвост — не четырнадцать
-- миллионов строк, а те двадцать тысяч, ради которых он и пришёл.
--
--
-- 2. ФУНКЦИЯ ЗАТИРАЛА НАСТРОЙКУ, А НЕ ЗАДАВАЛА ЕЁ
--
-- В 0046 `alter table ... set (...)` стоял безусловно, а `create_month_partition`
-- вызывается при КАЖДОМ старте хаба (Partitions.EnsureCurrentAndNextAsync), не
-- только когда партиции ещё нет. То есть любое значение, выставленное оператором
-- под конкретную нагрузку, возвращалось к зашитому при ближайшем перезапуске —
-- молча. Поймано ровно так: выставленный вручную порог трижды оказывался
-- прежним, и не потому, что ALTER не прошёл.
--
-- Теперь настройка ставится ТОЛЬКО при создании партиции. Значение в коде
-- остаётся тем, с чего партиция начинает жизнь; дальше это её собственная
-- настройка, и хаб в неё не лезет.

create or replace function public.create_month_partition(parent regclass, month date)
 returns void
 language plpgsql
as $function$
declare
    start_date date := date_trunc('month', month)::date;
    end_date   date := (start_date + interval '1 month')::date;
    part_name  text := format('%s_%s', parent::text, to_char(start_date, 'YYYY_MM'));
    existed    boolean := to_regclass(part_name) is not null;
begin
    execute format(
        'create table if not exists %I partition of %s for values from (%L) to (%L)',
        part_name, parent, start_date, end_date
    );

    -- Только на СВЕЖЕЙ партиции. Без автовакуума по вставкам append-таблица не
    -- убирается вовсе (мёртвых строк в ней нет, а обычный порог считается по
    -- ним) — но это стартовое значение, а не политика, которую надо навязывать
    -- при каждом перезапуске поверх того, что выставил человек.
    if not existed then
        execute format(
            'alter table %I set (autovacuum_vacuum_insert_threshold = 20000, '
            || 'autovacuum_vacuum_insert_scale_factor = 0)',
            part_name
        );
    end if;
end
$function$;


-- Существующим партициям — новое значение разово. Те, что 0046 уже пометила,
-- получают исправленную цифру; scale_factor остаётся нулевым, иначе порог
-- считался бы как 20 000 + 20% таблицы, то есть почти три миллиона строк на
-- партиции снимков — ровно та ошибка, из-за которой первая проверка показала,
-- что автовакуум «не срабатывает».
do $$
declare
    part record;
begin
    for part in
        select c.relname
          from pg_class c
          join pg_inherits i on i.inhrelid = c.oid
          join pg_class p on p.oid = i.inhparent
         where p.relkind = 'p' and c.relkind = 'r'
    loop
        execute format(
            'alter table %I set (autovacuum_vacuum_insert_threshold = 20000, '
            || 'autovacuum_vacuum_insert_scale_factor = 0)',
            part.relname);
    end loop;
end
$$;
