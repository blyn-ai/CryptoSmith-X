-- CryptoSmith X — миграция 0050: у mark/index-свечей появляется происхождение
-- «посчитано», потому что считать их наконец начали.
--
-- НАЙДЕНО ВОПРОСОМ «а где свечи?», отвеченным замером. На проде лежит 123 165
-- index-баров Avantis, свежих до минуты, — и ни одного из них не видно, потому
-- что все они `timeframe = 1`, а панель свечей открывается на часовом гране.
-- Причина ровно одна: RollupJob читает и пишет ТОЛЬКО market_candle. Таблица
-- market_price_candle (0032) не сворачивалась никогда и ни для кого — ни для
-- Avantis, ни для Binance, единственного, кто пишет туда же mark.
--
-- То есть это не дыра конкретной площадки. Это грань, которой не существовало
-- ни у одного ряда mark/index за всё время их сбора.
--
--
-- ЧТО ИМЕННО МЕШАЛО СХЕМЕ
--
-- 0032 объявила `source text not null check (source in ('rest', 'backfill'))`.
-- Оба значения описывают ДОСТАВКУ: обычный запрос и добор истории. Бара,
-- ПОСЧИТАННОГО из минуток, в этом перечне нет — и не могло быть, потому что
-- писателя у производных грани тогда не было вовсе.
--
-- 'derived' — то же слово, которым market_candle называет ровно это же (0001),
-- и оно должно совпадать: страница показывает source как есть, и «посчитано»
-- на одной таблице и «derived» на другой были бы двумя именами одного факта.
--
-- Расширение CHECK, а не снятие: перечень — это то, что не даёт появиться
-- четвёртому значению из опечатки в чьём-нибудь новом коллекторе.
--
-- NOT VALID здесь НЕ нужен, в отличие от 0035: старый CHECK снимается и
-- ставится новый, более широкий, и все существующие строки ('rest'/'backfill')
-- ему удовлетворяют по построению. Проверка существующих строк на таблице
-- такого размера — это секунды, и цена разовая.

alter table market_price_candle drop constraint if exists market_price_candle_source_check;

alter table market_price_candle add constraint market_price_candle_source_check
    check (source in ('rest', 'backfill', 'derived'));

comment on column market_price_candle.source is
    '''rest'' — обычный запрос к площадке, ''backfill'' — добор истории, '
    '''derived'' — бар, посчитанный из минуток этого же ряда (timeframe > 1, '
    'с 0050). Те же три слова и в том же значении, что у market_candle.';

comment on column market_price_candle.received_at is
    'Когда строка получена или посчитана. У этой таблицы нет updated_at, '
    'поэтому received_at служит и меткой касания: RollupJob читает по ней, '
    'какие бары изменились с прошлого прохода, а PriceCandleCollector '
    'переставляет её на каждой перезаписи.';
