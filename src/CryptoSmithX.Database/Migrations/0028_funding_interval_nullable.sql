-- ----------------------------------------------------------------------------
-- CryptoSmith X — миграция 0028: `funding_interval_hours` может быть NULL.
--
-- Колонка была `smallint not null check (> 0)`, и это заставляло адаптер, который
-- интервала не знает, назвать какое-нибудь число. WEEX так и делает:
-- `WeexFuturesMarketData.cs` подставляет 8, если батч-вызов фандинга промахнулся
-- мимо символа, — и комментарий там честно говорит, что это самый частый цикл
-- площадки, а не то, что площадка сообщила. В базе таких строк 541 из 1028, и
-- отличить их от настоящих восьмичасовых нельзя ничем: обе стороны выглядят
-- одинаково, потому что колонка не умеет сказать «не измерено».
--
-- Это не небрежность адаптера. Это наш контракт записи: у поля не было значения
-- для «неизвестно», поэтому единственный способ вставить строку — соврать. Дом
-- утверждает обратное — отсутствие измерения это прочерк, а не ноль и не
-- правдоподобное число, — и здесь схема этому мешала.
--
-- ПОЧЕМУ CHECK НЕ ТРОГАЕМ. `check (funding_interval_hours > 0)` пропускает NULL:
-- в SQL проверка со значением NULL даёт UNKNOWN, а не FALSE, и строка проходит.
-- Так что после снятия NOT NULL инвариант «если значение есть, оно
-- положительное» продолжает действовать сам, и переписывать его значило бы
-- сказать то же самое второй раз.
--
-- ЧТО НЕ ДЕЛАЕТСЯ ЗДЕСЬ И ПОЧЕМУ. Существующие 541 строку не обнуляем. Отличить
-- подставленные от настоящих невозможно, а обнулить все — значит выбросить и те,
-- что площадка действительно сообщила. Discovery перезаписывает поле на каждом
-- проходе (`DiscoveryCollector.cs:115`), так что после этой миграции строки
-- сами придут к правде за один час: настоящие вернутся числом, промахи станут
-- пустыми. Данные до верификации в любом случае одноразовые.
--
-- Не тронуты и другие площадки: у Kraken и Hyperliquid интервал — настоящая
-- константа венью (час), у Binance восьмёрка означает документированный дефолт
-- (`/fapi/v1/fundingInfo` перечисляет только отклонения, поэтому отсутствие там
-- есть утверждение), у `fake` — синтетика.
-- ----------------------------------------------------------------------------

alter table exchange_instrument
    alter column funding_interval_hours drop not null;

comment on column exchange_instrument.funding_interval_hours is
    'Часов между платежами фандинга, как их сообщает площадка. NULL означает «не измерено»: '
    'адаптер не получил интервал и не подставляет правдоподобное число вместо него. '
    'Ставка без своего периода — утверждение без единицы, поэтому потребитель, у которого '
    'здесь NULL, обязан показать прочерк, а не считать суточную нормализацию.';
