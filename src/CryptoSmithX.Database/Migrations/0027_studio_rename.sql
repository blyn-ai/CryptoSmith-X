-- ----------------------------------------------------------------------------
-- CryptoSmith X — миграция 0027: роль `arena_reader` становится `studio_reader`.
--
-- Публичный сайт переименован из Arena в Studio, и роль, под которой он ходит в
-- базу, обязана называться так же. Имя роли — не косметика: оно попадает в
-- строку подключения, в `pg_stat_activity` и в текст ошибки, и роль, которая
-- называется по-старому, через полгода будет читаться как чужая, оставшаяся от
-- чего-то забытого.
--
-- ПОЧЕМУ ОТДЕЛЬНОЙ МИГРАЦИЕЙ, А НЕ ПРАВКОЙ 0025. Файл 0025 уже применён на всех
-- живых базах, и `schema_version` помнит только его номер. Переписать его текст
-- значило бы, что файл описывает роль, которой в этих базах нет: свежая база
-- получила бы `studio_reader`, а существующая осталась бы с `arena_reader`, и
-- разошлись бы они молча. Миграция — это запись о том, что выполнилось, а не
-- описание желаемого; 0025 остаётся таким, каким его применили.
--
-- ALTER ROLE ... RENAME переносит все гранты вместе с ролью: права привязаны к
-- OID, а не к имени. Поэтому одиннадцать `grant select` из 0025 и один из 0026
-- переписывать не нужно, и здесь их нет намеренно — повторить их значило бы
-- завести второй источник правды о том, что именно разрешено публичной
-- поверхности.
--
-- ПРАВА. `alter role ... rename` — операция над ролью, а не над объектом схемы,
-- и владение таблицами её не разрешает: нужен CREATEROLE с admin option на
-- целевую роль либо суперпользователь. На VM клиента у владельца схемы нет ни
-- того, ни другого — `provision-host.sh` заводит его строкой `create role
-- marketdata login`, — и первая же попытка там кончается `42501 permission
-- denied to rename role` посреди прогона. Это ровно тот случай, который 0025
-- разбирает для своего `create role`, и здесь он ловится так же: отказ
-- переписывается в одну команду для оператора. `raise exception`, а не
-- `raise notice`: пропустить переименование значило бы записать 0027 как
-- применённую на базе, где роль по-прежнему `arena_reader`, а строка
-- подключения витрины уже отправляет `studio_reader` — витрина не авторизуется
-- никогда, и `schema_version` при этом утверждает, что всё на месте.
--
-- И ОТДЕЛЬНО: переименовать, а не создать заново. Гранты 0025 и 0026 выданы на
-- OID старой роли; роль с тем же именем, созданная с нуля, унаследует имя и
-- ничего больше. Ветка «уже переименована» поэтому проверяет право, а не имя:
-- иначе такая база тихо запишет 0027 как применённую, витрина авторизуется и
-- упадёт на первом же select — и `alter default privileges`, которого 0025
-- намеренно не ставит, эту дыру не закрыл бы тоже.
--
-- Пароль не трогается. Он и так подлежит ротации на каждом хосте: значение по
-- умолчанию лежит в docker-compose.prod.yml и известно всякому, кто видел
-- репозиторий.
-- ----------------------------------------------------------------------------

do $$
begin
    if exists (select 1 from pg_roles where rolname = 'studio_reader') then
        -- Роль с нужным именем — ещё не роль с нужными правами. Проверяем по
        -- `market_snapshot_latest`: она выдана в 0025 и без неё витрина не
        -- показывает ни одной цифры, так что отсутствие права означает роль,
        -- заведённую в обход переименования, а не частичный грант.
        --
        -- `to_regclass` здесь не перестраховка от несуществующей таблицы: роли в
        -- postgres общие на кластер, а гранты — на базу, поэтому `studio_reader`
        -- может существовать из-за СОСЕДНЕЙ базы того же кластера, где 0027 уже
        -- прошла. `has_table_privilege` на отсутствующей таблице не возвращает
        -- false, а падает, и мигратор получил бы «relation does not exist» вместо
        -- разбора. Судить о грантах на базе, где таблицы ещё нет, эта миграция
        -- не может и не берётся: в порядке мигратора 0001 всегда раньше 0027.
        if to_regclass('public.market_snapshot_latest') is not null
           and not has_table_privilege('studio_reader', 'market_snapshot_latest', 'select') then
            raise exception
                'роль studio_reader существует, но в этой базе у неё нет грантов витрины'
                using hint =
                    'роль заведена в обход переименования — либо её создали заново, либо она '
                    'осталась от соседней базы того же кластера, а гранты 0025 и 0026 в ЭТОЙ '
                    'базе лежат на arena_reader. Если arena_reader здесь есть и база в '
                    'кластере одна: sudo -u postgres psql -d marketdata -c "drop role '
                    'studio_reader; alter role arena_reader rename to studio_reader;". Если баз '
                    'несколько или arena_reader уже нет — переименование сломает соседей, '
                    'выдайте гранты по спискам из 0025 и 0026 на studio_reader. Затем повторить '
                    'деплой.';
        end if;

        -- Уже переименована, либо база создана после переименования. Ничего.
        return;
    end if;

    if exists (select 1 from pg_roles where rolname = 'arena_reader') then
        begin
            alter role arena_reader rename to studio_reader;
        exception when insufficient_privilege then
            raise exception
                'у роли % нет прав переименовать arena_reader', current_user
                using hint =
                    'один раз суперпользователем: sudo -u postgres psql -d marketdata -c '
                    '"alter role arena_reader rename to studio_reader;" — затем повторить '
                    'деплой. Именно переименовать: создание studio_reader с нуля оставит '
                    'гранты 0025 и 0026 на старой роли. Пароль rename не меняет, строку в '
                    '/opt/cryptosmithx/.env править не нужно.';
        end;
        return;
    end if;

    -- Ни той, ни другой. Это база, где 0025 не смог создать роль — на клиентской
    -- VM владелец базы заведён без CREATEROLE, и 0025 в этом случае поднимает
    -- ошибку с точной командой. Здесь не место её дублировать: если роли нет,
    -- значит 0025 уже сказал, что делать, и сказал подробнее.
    raise notice 'Ни arena_reader, ни studio_reader не существует — см. сообщение миграции 0025.';
end $$;
