-- ============================================================================
-- CryptoSmith X — миграция 0008: ручное управление сбором по инструменту.
--
-- До сих пор у инструмента был только НАБЛЮДАЕМЫЙ статус биржи (trading/halted/
-- delisted и т.д.) — это факт о рынке, его пишет discovery. Появляется отдельная,
-- НАШЕ решение: collect — собирать ли по инструменту снапшоты/свечи/глубину/
-- funding. Одно не подменяет другое: инструмент может быть trading на бирже, но
-- collect=false у нас (шумный, неинтересный, экономим лимиты), и наоборот.
--
-- Важно: collect выключает только сбор данных, НЕ наблюдение. discovery
-- продолжает видеть и обновлять такие инструменты (статус, last_seen, raw_json) —
-- иначе выключенный инструмент «застыл» бы и мы не заметили бы его делистинг.
-- Снапшот/свечи/глубина/funding в Hub пропускают строки с collect=false.
--
-- Правка тумблера пишет все четыре поля (значение + заметку + когда + кем) —
-- это решение оператора, и оно должно быть подотчётным, как и правки биржи в 0007.
--
-- Заодно у asset появляется аудит правок (updated_at/updated_by): на новом экране
-- Assets имя и заметку канона можно редактировать, и эта правка — тоже решение
-- оператора, подотчётное так же, как правки exchange и setting.
--
-- Что НЕ вошло и почему:
--   * Отдельный журнал изменений collect (кто/когда/что, историей) — как и в
--     0007, здесь достаточно «последний, кто трогал»; полноценный аудит-лог это
--     отдельная задача.
--   * Управление сбором на уровне актива или котировки — решение принимается по
--     конкретному листингу, гуртом это не выключается.
-- ============================================================================

alter table exchange_instrument
    add column collect            boolean not null default true,
    add column collect_note       text,
    add column collect_changed_at timestamptz,
    add column collect_changed_by text;

alter table asset
    add column updated_at timestamptz,
    add column updated_by text;

comment on column asset.updated_by is
    'Кто в последний раз правил имя/заметку канона в UI (null у сидов и авторегистрации).';

comment on column exchange_instrument.collect is
    'НАШЕ решение: собирать ли по инструменту снапшоты/свечи/глубину/funding. '
    'Не путать со status — тот наблюдаемый (что говорит биржа). discovery видит и '
    'обновляет инструмент независимо от collect; выключается только сбор данных.';
comment on column exchange_instrument.collect_note is
    'Почему сбор выключен/включён — заметка оператора, показывается в UI.';
comment on column exchange_instrument.collect_changed_at is
    'Когда collect в последний раз меняли через UI.';
comment on column exchange_instrument.collect_changed_by is
    'Кто в последний раз менял collect (User.Identity.Name).';
