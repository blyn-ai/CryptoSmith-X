-- ============================================================================
-- 0016 — свой водяной знак у коллектора, отдельно от last_success_at.
--
-- Роллап держал прогресс в last_success_at: «когда проход закончился». Пока
-- проход укладывается в интервал, это одно и то же. Как только он отстал на
-- часы, разница становится смертельной: докуда данные обработаны — записать
-- некуда, поэтому проход обязан догнать всё отставание разом, упирается в
-- command timeout, last_success_at не двигается, и следующий проход берётся за
-- то же самое, только большее. Отставание в 4 часа так не отрабатывается
-- никогда — это ровно то, что случилось на проде 2026-09-02.
--
-- watermark_at — «докуда обработано», и его можно двигать шагами: проход берёт
-- ограниченный кусок, дописывает знак и на следующем витке идёт дальше. Столбец
-- пишет сам джоб; upsert статуса в ExchangeWorker перечисляет колонки поимённо
-- и эту не трогает.
-- ============================================================================

alter table collector_status add column watermark_at timestamptz;

comment on column collector_status.watermark_at is
    'Докуда коллектор обработал источник (не путать с last_success_at — когда он последний раз отработал).';
