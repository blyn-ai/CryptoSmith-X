-- ============================================================================
-- CryptoSmith X — миграция 0051: у переноса позиции две стороны, и обе
-- хранятся.
--
-- ЕДИНИЦА ИЗМЕРЕНА, А НЕ УГАДАНА. Колонки carry не заводились до сих пор по
-- честной причине: площадка публикует `fundingRate{long,short}` и
-- `marginFee{long,short}`, но ни в одной схеме SDK единица не объявлена, а
-- `fundingFeePerHourP`, у которого единица документирована («%»), равен нулю.
-- Писать число без единицы — соврать дважды.
--
-- Замер, который это закрыл. Документация площадки даёт якорь: «On RWAs (FX,
-- commodities) holding costs can run below 3% a year». Проверено по живому
-- каталогу, сумма funding + margin fee:
--
--   ПРИ ЧТЕНИИ «ПРОЦЕНТ В ЧАС»      ПРИ ЧТЕНИИ «ДОЛЯ В ЧАС»
--     WTI     2.50 %/год              250 %/год
--     GBP     5.33 %/год              533 %/год
--     EUR     7.46 %/год              746 %/год
--     BTC     4.38 %/год              438 %/год
--     ETH     9.64 %/год              964 %/год
--     SOL    11.13 %/год             1113 %/год
--
-- WTI попадает в заявленное «ниже 3% в год» ровно при первом чтении, и при нём
-- же каждая крипто-строка — обычная ставка переноса. При втором не выживает ни
-- одна строка: годовая стоимость удержания в 250-1368% не бывает ни у одного
-- из этих активов. ПРОЦЕНТ В ЧАС.
--
--
-- ПОЧЕМУ НЕ ОДНО ЧИСЛО В ОБЩУЮ СТРОКУ
--
-- market_snapshot.funding_rate — ОДИН платёж, потому что на книжной площадке он
-- один: лонги платят шортам ровно столько, сколько шорты получают. Здесь не так.
-- ETH прямо сейчас: лонг платит 0.00109998 %/ч, шорт получает 0.00114364 %/ч —
-- это НЕ зеркало, потому что вторая сторона тут пул, а не встречный трейдер.
-- Свести их в одно число — потерять именно тот факт, который отличает эту
-- модель рынка от книжной.
--
-- Поэтому в общую строку идёт сторона лонга (её колонка и означает: сколько
-- платит длинная позиция), а обе стороны целиком — сюда, в набор, где уже лежит
-- всё остальное, что у книжных площадок NULL-по-модели. Тот же приём и по той
-- же причине, что в 0044.
--
-- margin_fee — это borrow fee, вторая половина «net rate» по документации
-- площадки: funding обменивается с другими трейдерами, borrow платится
-- поставщикам ликвидности. Две разные величины, и складывать их в хранении
-- нельзя — читатель сложит сам, имея обе.

alter table vault_pair_state
    add column if not exists funding_long_p_hour    double precision,
    add column if not exists funding_short_p_hour   double precision,
    add column if not exists margin_fee_long_p_hour double precision,
    add column if not exists margin_fee_short_p_hour double precision;

comment on column vault_pair_state.funding_long_p_hour is
    'Ставка фандинга для ДЛИННОЙ стороны, ПРОЦЕНТ В ЧАС (единица измерена, см. 0051). '
    'Положительное — платит, отрицательное — получает.';
comment on column vault_pair_state.funding_short_p_hour is
    'То же для короткой стороны. НЕ минус длинной: контрагент здесь пул, и стороны '
    'несимметричны — ETH на момент миграции 0.00109998 против -0.00114364.';
comment on column vault_pair_state.margin_fee_long_p_hour is
    'Borrow fee длинной стороны, процент в час. Вторая половина «net rate» площадки: '
    'фандинг обменивается с трейдерами, borrow платится поставщикам ликвидности. '
    'Хранится отдельно — складывает читатель, а не запись.';
comment on column vault_pair_state.margin_fee_short_p_hour is
    'Borrow fee короткой стороны, процент в час.';
