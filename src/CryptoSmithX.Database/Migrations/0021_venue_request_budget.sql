-- ============================================================================
-- 0021 — у венью появляется бюджет запросов, который наконец кто-то считает.
--
-- 0019 завёл уровень `exchange` ровно ради одной вещи: лимит запросов на IP
-- общий у всех площадок одной биржи. Уровень появился, а числа так и не было —
-- предпосылка была объявлена и осталась неисполненной. Каждый вызывающий пейсил
-- себя сам и в одиночку: `DepthCollector` держал паузу 50 мс (≈20 req/s),
-- `WeexOpenInterestFeed` — 150 мс (≈6.7 req/s), `HyperliquidBookFeed` — 800 мс.
-- Никто из них не знал о существовании остальных. Три «потолка» на одну венью —
-- это не потолок, это три независимых потока в одну трубу.
--
-- Хуже другое. Последовательный обход стакана платит сетевую задержку по разу
-- на символ: на проде WEEX проход по 1005 инструментам занимал 361 с при такте
-- 60 с (реальная каденция 421 с, загрузка цикла 86 %), при простаивающем хосте
-- (load 0.34). Ограничением была не биржа, а то, что мы ждали её по одному.
-- Отсюда две разные величины в этой миграции, и их важно не путать:
--
--   request_budget_per_s    — сколько запросов в секунду мы себе разрешаем;
--   max_concurrent_requests — сколько их может лететь одновременно.
--
-- Первое защищает биржу от нас. Второе защищает нас от задержки: при том же
-- потолке в 20 req/s восемь одновременных запросов превращают те же 361 с
-- примерно в 50 с, не прибавив бирже ни одного запроса в секунду.
--
-- ---------------------------------------------------------------------------
-- Откуда взяты числа, и где мы честно признаём, что их нет
-- ---------------------------------------------------------------------------
-- `request_budget_source` существует потому, что «20 req/s для WEEX» жило в
-- наших комментариях с коммита 100f605 (`WeexOpenInterestFeed.cs`) как якобы
-- документированное, без ссылки и без замера, и оттуда расползлось: комментарий
-- в `DepthCollector` обосновывает ту же паузу ссылкой на документацию KRAKEN,
-- применённой к WEEX «по аналогии». У WEEX сегодня опубликован V3: страница
-- https://www.weex.com/api-doc/contract/QuickStart/AccessRestrictions и поле
-- `rateLimits` в ответе GET /capi/v3/market/exchangeInfo дают 2000 весов / 10 с
-- на IP, общий пул на все V3-эндпоинты рынка (GET /capi/v3/market/depth весит 1
-- и требует ровно один symbol — отсюда 200 req/s для запросов веса 1). Наш
-- клиент ходит в `/capi/v2/market/*`, а не в v3, но та же страница лимитов
-- говорит прямо: ограничение считается по IP, а не по ключу и не по конкретному
-- эндпоинту, значит это один и тот же счётчик для v2 и v3 с одного адреса, и
-- число применимо к нам, а не только к вызовам v3. Поэтому WEEX ниже —
-- единственная строка с `documented`, а не `assumed`.
--
-- Значения source: 'documented' — есть страница вендора с числом, из которого
-- наше выводится; 'measured' — мы получили 429 и знаем, где стенка; 'assumed' —
-- мы выбрали сами. Читать колонку следует буквально: разница между 'documented'
-- и 'assumed' — это разница между «биржа так сказала» и «мы так решили», и она
-- нужна тому, кто через год будет поднимать потолок.
--
-- У Kraken страница лимитов есть, но публичные рыночные эндпоинты в ней
-- выведены из-под бюджета — применимого числа она не даёт, и потолок там
-- остаётся наш. Binance публикует веса, а не запросы. У Hyperliquid при
-- разведке ничего не нашлось. Три потолка из четырёх по-прежнему выбраны нами,
-- и колонка говорит об этом прямо; WEEX — единственное исключение, и ниже
-- указано, откуда именно взято его число.
--
-- ---------------------------------------------------------------------------
-- Что было отвергнуто
-- ---------------------------------------------------------------------------
-- * Держать бюджет на сегменте. Тогда `kraken-futures` и будущий `kraken-spot`
--   имели бы по своему потолку и молча делили бы один IP — ровно та ошибка,
--   ради устранения которой в 0019 появился уровень венью.
-- * Хранить бюджет в весах (как Binance и WEEX V3), а не в запросах. Честнее по
--   форме, но вес зависит от эндпоинта, а у половины наших вызовов вендор веса
--   не публикует. Получилась бы точная на вид модель, собранная из выдуманных
--   коэффициентов. Запрос в секунду — грубее, но каждое число в нём настоящее.
-- * Считать потолок из замеренной длительности развёртки автоматически. Консоль
--   уже показывает реальную каденцию (`SegmentCadence`, `DepthSweepSeconds`),
--   и этого достаточно, чтобы человек увидел эффект и подкрутил число руками.
--   Автоматика, которая сама поднимает темп до первого 429, — это машина для
--   получения 429.
-- * Дать колонкам DEFAULT. Умолчание означало бы, что новая биржа получает
--   бюджет молча; пусть тот, кто заводит венью, назовёт число и его источник.
-- ============================================================================

