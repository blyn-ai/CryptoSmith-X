-- Венью без бюджета — это венью, чей потолок никто не считает: ровно то
-- состояние, из которого эта миграция выводит. Пусть падает здесь, а не в
-- рантайме при первом же обходе стакана.
do $$
declare missing text;
begin
    select string_agg(code, ', ') into missing from exchange where request_budget_per_s is null;
    if missing is not null then
        raise exception 'биржи без бюджета запросов: %', missing;
    end if;
end $$;

alter table exchange alter column request_budget_per_s    set not null;
alter table exchange alter column max_concurrent_requests set not null;
alter table exchange alter column request_budget_source   set not null;

alter table exchange add constraint exchange_request_budget_per_s_check
    check (request_budget_per_s between 1 and 10000);
alter table exchange add constraint exchange_max_concurrent_requests_check
    check (max_concurrent_requests between 1 and 64);
alter table exchange add constraint exchange_request_budget_source_check
    check (request_budget_source in ('documented', 'measured', 'assumed'));

