-- ============================================================================
-- CryptoSmith X — миграция 0055: binance-spot получает адрес и СВОЙ потолок.
--
-- Хост у спота другой — api.binance.com против fapi.binance.com у фьючерсов, —
-- и потолки у них независимые, замерено 2026-09-13 по заголовку
-- x-mbx-used-weight-1m: 6000 весов в минуту на споте против 2400 на фьючерсах.
-- После 0054 гейт ключуется на хост, поэтому свой потолок здесь не «ещё одна
-- настройка», а единственный способ не отдать споту потолок фьючерсов.
--
-- Сколько стоит проход, замерено на живой площадке:
--
--     exchangeInfo?showPermissionSets=false   вес 40   6546 КБ  3698 строк
--     ticker/24hr        (без символа)        вес 80   1850 КБ  3701 строка
--     depth limit=5000   (на символ)          вес 250
--
-- Снимок закрывается ОДНИМ вызовом: ticker/24hr несёт и оборот, и живой верх
-- стакана с размерами, поэтому ticker/bookTicker не зовётся вовсе.
--
-- Потолок 20 запросов в секунду — это не 6000/60. Это осознанно меньше: вес
-- запроса от 4 до 250, и «запросов в секунду» у гейта не знает, какой именно
-- запрос пройдёт следующим. 20/с с запасом покрывает снимок раз в минуту и
-- обход глубины по десятку инструментов, и оставляет место фьючерсам, которые
-- на этот потолок не влияют и не попадают под него.
--
-- Колонки «источник» у сегмента нет — она есть только у биржи, и заводить её
-- здесь незачем: число выше выведено из заголовка самой площадки, и откуда —
-- написано в этих строках, а не в ещё одном поле, которое придётся заполнять
-- всем остальным.
-- ============================================================================

update segment
   set base_url = 'https://api.binance.com',
       request_budget_per_s = 20,
       updated_at = now(),
       updated_by = '0055'
 where code = 'binance-spot';
