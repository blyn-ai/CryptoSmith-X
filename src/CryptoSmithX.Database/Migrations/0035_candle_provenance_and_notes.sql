-- Применённый файл не правится, поэтому причины живут здесь, а не в
-- будущей правке 0001/0028/0032.
--
-- 1. qty_unit, contract_form, contract_type, expires_at — не добавлены.
--    Скоуп V1 (0001): линейные перпетуалы, dated и инверсные discovery
--    пропускает. Для линейного контракта qty_base = qty × contract_multiplier
--    верно для КАЖДОЙ строки КАЖДОЙ таблицы; «множитель 1» и «в base» — одно
--    утверждение, не два независимых факта, которые могли бы разойтись.
--    Информация теряется только у инверсных контрактов (там множитель — в
--    quote, не в base) — их нет в скоупе ни одной подключённой площадки.
--    Когда придут: нужен contract_form плюс валюта множителя, а не отдельный
--    qty_unit — тот отвечал бы не на тот вопрос. До той площадки колонки
--    были бы без читателя.
--
-- 2. volume_quote на market_candle — отвергнуто в 0001 с причиной (нет у
--    Hyperliquid и Kraken; для оценки ликвидности есть turnover_24h на
--    снапшоте), и причина не изменилась — эта серия её не переоткрывает.
--    Единица volume ("в единицах количества инструмента") зафиксирована
--    комментарием ещё в 0001.
--
-- 3. status_raw, отдельное значение delisting, отдельное значение unknown —
--    не заводятся. Сырой статус биржи и так лежит в raw_json построчно у
--    каждого прохода discovery — второе поле дублировало бы то, что уже
--    есть. delisting не наблюдается единообразно на четырёх площадках как
--    отдельное состояние — здесь делистинг определяет механизм
--    delist_after_missed_discoveries (0014), не сырой статус самой биржи.
--    unknown не нужен: статус в листинге есть у всех четырёх подключённых
--    площадок без исключения. Появится площадка, где какое-то из этих трёх
--    станет наблюдаемым фактом, а не нашей интерпретацией, — тогда и здесь.
--
-- 4. Событийная таблица под сами события ликвидации (не агрегат) —
--    отложена. Единственный наблюдаемый писатель такого потока сегодня —
--    Binance forceOrder (сэмпл ≤ 1 события в секунду на символ — это
--    свойство площадки, не наше ограничение сбора); без него у таблицы нет
--    писателя, и заводить её раньше кода значило бы завести пустую таблицу
