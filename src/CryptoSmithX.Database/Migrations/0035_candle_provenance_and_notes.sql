-- B. market_candle — единственная историческая таблица без провенанса
-- ----------------------------------------------------------------------------
-- trade, book_topn, market_price_candle, open_interest_history,
-- liquidation_volume_history (0032), funding_rate_history (0033) — у всех
-- есть received_at/known_from/source. market_candle — нет, хотя она
-- исторична ровно так же (свечи не ротируются, 0001).
--
-- updated_at НЕ заменяет received_at. Комментарий на market_candle_incomplete
-- (0001) говорит прямо: джоб бэкфилла повторно выкачивает закрытое окно и
-- пересчитывает бар — updated_at на такой строке растёт, хотя момент, когда
-- эти конкретные минутки были ПОЛУЧЕНЫ от биржи, давно в прошлом и этим
-- пересчётом не меняется. «Последняя запись или пересчёт» и «когда получено»
-- — разные факты, и до этой миграции второй нигде не хранится.
-- ПОЧЕМУ CHECK ОТДЕЛЬНО И NOT VALID. Первая версия этого файла писала CHECK прямо в
-- ADD COLUMN — и деплой на TEST упал: Npgsql убил команду своим клиентским таймаутом в
-- 30 с. Замер на TEST (15 467 356 строк, 3 партиции, обе формы прогнаны в транзакции с
-- откатом): три ADD COLUMN без CHECK — 50 мс, тот же ADD COLUMN с инлайновым CHECK —
-- 4649 мс. Разница — полная валидация: Postgres сканирует каждую существующую строку,
-- проверяя ограничение, которому они удовлетворяют ТРИВИАЛЬНО, потому что колонка
-- заводится этим же оператором и во всех существующих строках она NULL, а NULL проходит
-- любой CHECK. Четыре с половиной секунды ACCESS EXCLUSIVE на таблице, в которую
-- непрерывно пишут два сборщика, — плата ни за что.
--
-- NOT VALID убирает ровно этот скан и НЕ ослабляет ограничение для будущих записей:
-- NOT VALID означает «не проверять то, что уже лежит», а не «не проверять то, что придёт».
-- VALIDATE CONSTRAINT следом не делается сознательно — валидировать нечего, все
-- существующие значения NULL по построению, и единственным эффектом был бы тот самый
-- скан, ради устранения которого всё и написано.
--
-- lock_timeout — про вторую половину той же аварии. Сам DDL быстрый, но сначала ему нужна
-- блокировка, а market_candle пишут CandleCollector и RollupJob; в момент деплоя старый hub
-- ещё дописывал. Без lock_timeout ожидание съедает клиентский бюджет и падает невнятным
-- «Exception while reading from stream»; с ним ожидание ограничено и ошибка называет
-- причину. 60 с заведомо меньше таймаута команды у мигратора (180 с, задан строкой
-- подключения в deploy/docker-compose*.yml), поэтому первым срабатывает именно этот,
-- говорящий предел.
set local lock_timeout = '60s';

alter table market_candle
