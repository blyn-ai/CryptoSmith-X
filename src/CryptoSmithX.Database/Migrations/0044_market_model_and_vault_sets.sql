insert into segment_dataset_capability (segment_code, dataset_code, capability_key)
select sd.segment_code, sd.dataset_code, k.key
  from segment_dataset sd
 cross join capability_key k
 where sd.dataset_code in ('vault_pair_state', 'vault_state')
 on conflict (segment_code, dataset_code, capability_key) do nothing;


-- ----------------------------------------------------------------------------
-- 6. Сегмент Avantis: модель и адрес сокета
-- ----------------------------------------------------------------------------
-- ЗАМЕР ОТМЕНИЛ ВТОРОЙ ВЫВОД ПЛАНА. §3 постановила «ws_url пустой: у Avantis
-- нашего сокета нет, поток Pyth — это не поток площадки». Неверно:
-- data.avantisfi.com вещает Socket.IO без авторизации и рассылает изменения
-- каталога — фандинг, OI, спред, часы. Это СОБСТВЕННЫЙ сокет площадки, и
-- запрет плана («не звать поток Pyth живым от площадки») к нему не относится —
-- он остаётся в силе для прямой подписки на Pyth мимо Avantis.
--
-- Значение ставится здесь, потому что ветка
-- !string.IsNullOrWhiteSpace(config.WsUrl) в ExchangeWorker поднимает фид
-- штатно, как у Kraken и WEEX. Транспорт при этом ДРУГОЙ: это Socket.IO поверх
-- Engine.IO (рукопожатие, кадры 42["event",…], ping/pong), а не голый
-- WebSocket — WsConnection здесь не подойдёт, и это отдельная работа коннектора,
-- не reuse.
--
-- base_url — data-сервис: каталог GET /v2/trading отдаёт 120 пар одним вызовом
-- (362 КБ, 0.81 с, без ключа). Состояние хранилища живёт на другом хосте
-- (tx-builder.avantisfi.com/v2/lp/state) и адресуется коннектором отдельно:
-- одна строка сегмента не держит два базовых адреса, и выдумывать колонку под
-- второй ради одной площадки рано.
update segment
   set market_model = 'oracle_vault',
       base_url     = coalesce(base_url, 'https://data.avantisfi.com'),
       ws_url       = coalesce(ws_url, 'https://data.avantisfi.com')
 where code = 'avantis-perp';


-- ----------------------------------------------------------------------------
-- Чего здесь нет и почему
-- ----------------------------------------------------------------------------
-- КОЛОНОК СТАВОК CARRY (скос и borrow). У Avantis нет дискретного платежа
-- фандинга — есть непрерывный carry, и компоненты он публикует раздельно:
-- fundingRate{long,short}, marginFee{long,short}, min/maxShortBorrowFee,
-- accPerOiLong/Short. Писать их в funding_rate нельзя: та колонка — ОДИН платёж
-- лонг↔шорт за интервал, другая величина с другой единицей. Пара
-- (funding_rate, funding_interval_hours) = (NULL, NULL) под market_model
-- читается однозначно, и 0028 менять не надо.
--
-- Своих колонок они не получили по одной причине: ЕДИНИЦА НЕ ИЗМЕРЕНА.
-- fundingRate у BTC даёт 0.00120006 при fundingFeePerHourP = 0 — то есть это
-- заведомо разные величины, и период второй нигде не опубликован: /v2/meta
-- несёт только ончейн-масштабы, его глоссарий описывает поля торгового интента,
-- а питоновский SDK — проверено по исходникам — величину НЕ конвертирует вовсе,
-- пробрасывает моделью FundingRate{long,short} как есть. Конверсия живёт на
-- сервере площадки.
--
-- Имя с единицей (funding_rate_1h) утверждало бы период, которого никто не
-- мерил; имя без единицы приглашает потребителя нормализовать наугад, что 0028
-- прямо запрещает. Поэтому — следующей миграцией, когда единица будет измерена.
-- Миграций сорок три; сорок пятая дешевле неверного имени в данных.
--
-- OHLC ОРАКУЛА тоже не требует схемы: market_price_candle (0032) с
-- series = 'index' держит ровно это. §0 нашёл живой публичный источник, о
-- котором план не знал — feed-v3.avantisfi.com/v1/shims/tradingview/history,
-- разрешения 1/5/60/240/D, 1440 минутных баров за сутки без пропусков, работает
-- и на акциях. Объёма в барах НЕТ (это ценовой фид, не лента), поэтому именно
-- candles_index, а не candles: market_candle остаётся пустым, пока нет ленты
-- исполнений — а её у площадки нет ни на одном эндпоинте.
