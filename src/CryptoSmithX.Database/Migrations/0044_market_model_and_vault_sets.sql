insert into dataset (code, name, kind, description, default_mode, default_interval_s, default_retention_days)
values
    ('vault_pair_state', 'Vault pair state', 'feed',
     'OI по сторонам, потолки и входы функции импакта на vault-backed площадке',
     'disabled', 60, 90),
    ('vault_state', 'Vault state', 'feed',
     'Состояние пула ликвидности площадки: share price, утилизация, потолок депозита',
     'disabled', 60, 90)
on conflict (code) do nothing;

insert into segment_dataset (segment_code, dataset_code, mode, note, updated_by)
select s.code, d.code, 'disabled', null, '0044 migration'
  from segment s
 cross join (values ('vault_pair_state'), ('vault_state')) as d(code)
 on conflict (segment_code, dataset_code) do nothing;

-- we_implement НЕ проставляется здесь: адаптер объявит его сам при сборке
-- (ExchangeWorker.Build), а не эта миграция от его имени. Честное «не знаем» до
