-- ----------------------------------------------------------------------------
-- 1. segment.market_model — почему это имя модели, а не ось
-- ----------------------------------------------------------------------------
-- Avantis приносит впервые ПУСТОЕ ПОЛЕ, которое пусто по модели рынка, а не
-- потому что мы не получили. Четыре колонки котировки (bid/ask и размеры) и
-- пара (funding_rate, funding_interval_hours) у него пусты не оттого, что фид
-- молчит: у этого рынка нет двух сторон и нет дискретного платежа фандинга.
-- 0030 сняла not null со всех одиннадцати полей снимка и сделала пустоту
-- выразимой; эта колонка делает её ОБЪЯСНИМОЙ. Без неё «нет по природе» и
-- «не получили» на странице неразличимы, а вся эта система построена ровно на
-- том, чтобы они различались.
--
-- На СЕГМЕНТЕ, а не на инструменте: у Avantis книги нет нигде, ни на одной
-- паре, и NULL-по-модели у спота уже объяснён сегментом (kind).
--
-- ИМЕНЕМ МОДЕЛИ, а не осями («откуда цена / как исполняется / как устроена
-- ликвидность»). Разложить на оси можно будет, когда появится ВТОРАЯ небуковая
-- площадка и станет видно, какие оси реальны. Пока это была бы конструкция,
-- выведенная из одного случая. Третья модель — третье имя, одна строка CHECK.
--
-- default 'orderbook' закрывает пять существующих сегментов разом и без
-- перечисления: всё, что было до этой миграции, книгой и является.
alter table segment
    add column if not exists market_model text not null default 'orderbook';

alter table segment
    drop constraint if exists segment_market_model_check;

alter table segment
    add constraint segment_market_model_check
    check (market_model in ('orderbook', 'oracle_vault'));

comment on column segment.market_model is
    'Как устроен рынок этого сегмента. orderbook — встречный ордер и книга; '
    'oracle_vault — контрагент это пул ликвидности, цену даёт оракул, книги нет. '
    'Это ИМЯ МОДЕЛИ, а не ось: третья модель получит третье имя, а не разложение '
    'на признаки, выведенное из одного случая. Объясняет, почему у строки пусты '
    'bid/ask, их размеры, полосы глубины и пара (funding_rate, '
    'funding_interval_hours): «нет по природе рынка», а не «не получили».';


-- ----------------------------------------------------------------------------
-- 2. market_open — торгуется ли инструмент прямо сейчас
-- ----------------------------------------------------------------------------
-- Второе, что приносит Avantis: рынок, который закрыт ПО РАСПИСАНИЮ, а не
-- потому что фид умер. Сегодня возраст считается по received_at, и площадка,
-- отвечающая замёрзшим оракулом в закрытую сессию, показала бы пятничную цену
-- как двухсекундную. У Avantis это не гипотетика: из 120 пар 28 акций, 10
-- форекса, 2 металла — у всех сессии.
--
-- ИМЯ ПО СМЫСЛУ, ПРОВЕНАНС В КОММЕНТАРИИ — так же, как index_price у Binance
-- остаётся «индексом Binance», хотя это композит чужих площадок. Отвергнуто
-- feed_open: оно называет МЕХАНИЗМ, а у следующей площадки с собственным
-- флагом сессии никакого «фида» не будет.
--
-- NULL = площадка не публикует. Календарей, таймзон и праздников мы не храним
-- (у Avantis строка расписания в кадре есть — и мы её не берём): их мы получим
-- неверно и проверить не сможем. Только заявление на момент наблюдения.
alter table market_snapshot_latest add column if not exists market_open boolean;
alter table market_snapshot        add column if not exists market_open boolean;

comment on column market_snapshot_latest.market_open is
    'Торгуется ли инструмент в момент наблюдения, по заявлению площадки. '
    'NULL = площадка не публикует такого флага (все пять сегментов до 0044). '
    'Avantis: ретранслирует Pyth attributes.isOpen — провенанс чужой, смысл наш. '
    'Расписание/календарь НЕ хранится: только заявление на момент наблюдения.';
comment on column market_snapshot.market_open is
    'См. market_snapshot_latest.market_open.';


-- ----------------------------------------------------------------------------
-- 3. oi_quote — ноционал открытого интереса, как его публикует площадка
-- ----------------------------------------------------------------------------
-- ЗАМЕР ОТМЕНИЛ ПРЕМИСУ ПЛАНА. §2.5 предполагала, что количества Avantis не
-- даёт и open_interest останется NULL. Живой кадр (2026-09-11, 120 пар) даёт
-- ОБЕ единицы на каждой паре: coinOI{long,short} — количество базового актива,
-- openInterest{long,short} — ноционал в USD. Делить ничего не надо, и запрет
-- «не выводить open_interest делением ноционала на цену» остаётся в силе,
-- просто не наступает.
--
-- ЧТО САМА ПЛОЩАДКА НАЗЫВАЕТ OPEN INTEREST — проверено, а не предположено:
-- pairOI == openInterest.long + openInterest.short на всех 120 парах до
-- последнего знака, и totalOi == сумма pairOI. То есть OI пары у неё это
-- long + short. Это и пишется.
--
-- open_interest_history.oi_quote существует с 0032 и держит опубликованный
-- ноционал; снимок его не имел. Теперь имеет — та же величина, тот же смысл.
alter table market_snapshot_latest add column if not exists oi_quote double precision;
alter table market_snapshot        add column if not exists oi_quote double precision;

comment on column market_snapshot_latest.oi_quote is
    'Открытый интерес в КОТИРУЕМОМ активе (ноционал), как публикует площадка — '
    'не наш расчёт и никогда не open_interest × цена. Парная величина к '
    'open_interest, который остаётся в единицах количества. Та же величина, что '
    'open_interest_history.oi_quote. NULL = площадка ноционала не публикует.';
comment on column market_snapshot.oi_quote is
    'См. market_snapshot_latest.oi_quote.';


-- ----------------------------------------------------------------------------
-- 4. Два набора, а не один — потому что зернистость разная
-- ----------------------------------------------------------------------------
-- План называл один набор vault_state. Это ошибка плана, и она видна на данных:
-- входы импакта и OI по сторонам — наблюдение ОБ ИНСТРУМЕНТЕ, а состояние
-- хранилища (share price, утилизация, потолок депозита) — наблюдение О ВЕНЬЮ
-- ЦЕЛИКОМ. Одним ключом не покрыть, и склейка заставила бы либо дублировать
-- состояние хранилища на каждую пару, либо оставлять инструментальные колонки
-- пустыми в строке про венью. Обе формы — ложь о том, что было измерено.
--
-- vault_state с ключом на СЕГМЕНТ — первая таблица наблюдений без инструмента,
-- прецедента в схеме нет. Это нормально: наблюдение действительно о венью.

create table if not exists vault_pair_state (
    exchange_instrument_id integer      not null references exchange_instrument(id),
    received_at            timestamptz  not null,

    -- OI по сторонам. Обе единицы, как публикует площадка (см. §3 выше).
    oi_long_base    double precision,
    oi_short_base   double precision,
    oi_long_quote   double precision,
    oi_short_quote  double precision,

    -- Потолки: то, чем площадка ограничивает набор позиции.
    oi_max_quote    double precision,
    oi_block_limit  double precision,

    -- ВХОДЫ функции импакта, не отсчёты при выбранных размерах. Спред Avantis —
    -- функция (сторона, ноционал, момент); хранить её значения при трёх-четырёх
    -- размерах значило бы выбрать размеры навсегда и потерять всё остальное.
    -- Из этих входов стоимость ЛЮБОГО ноционала воспроизводима потом, а выбор
    -- размеров становится кодом, а не схемой.
    --
    -- Сравнение с книгами при равном ноционале — на ЧТЕНИИ, обращением функции,
    -- и никогда не в depth_*bps: те документированы как измерение книги (0035 §A),
    -- а у этого рынка книги нет.
    depth_above_1pct  double precision,
    depth_below_1pct  double precision,
    liquidity_buy     double precision,
    liquidity_sell    double precision,
    price_impact_mult double precision,
    skew_impact_mult  double precision,
    spread_p          double precision,
    decayed_vol       double precision,

    primary key (exchange_instrument_id, received_at)
);

comment on table vault_pair_state is
    'Наблюдение о ПАРЕ на vault-backed площадке: OI по сторонам в обеих единицах, '
    'потолки и ВХОДЫ функции ценового импакта. Отдельный набор, а не колонки '
    'общей строки: всё это NULL-по-модели для книжных площадок, то есть для '
    'целого класса венью. Входы, а не отсчёты при выбранных размерах — см. '
    'комментарии к колонкам.';
comment on column vault_pair_state.depth_above_1pct is
    'Ноционал, двигающий цену на 1% вверх, как публикует площадка '
    '(pairParams.onePercentDepthAbove). Вход функции импакта, НЕ измерение книги: '
    'книги у этого рынка нет, и в depth_*bps этому значению не место.';
comment on column vault_pair_state.spread_p is
    'Фиксированный спред пары в процентах, как публикует площадка. Это НЕ '
    'bid/ask: размерозависимая часть считается из входов импакта выше.';

create table if not exists vault_state (
    segment_code  text         not null references segment(code),
    received_at   timestamptz  not null,

    -- ERC-4626 транш: контрагент каждой сделки на этой площадке. Для
    -- vault-backed венью это то же, чем для книжной является глубина.
    total_assets_quote     double precision,
    total_supply_shares    double precision,
    share_price_quote      double precision,
    utilization_ratio      double precision,
    deposit_cap_quote      double precision,
    withdraw_threshold_quote double precision,

    primary key (segment_code, received_at)
);

comment on table vault_state is
    'Наблюдение о ВЕНЬЮ целиком: состояние пула ликвидности, который выступает '
    'контрагентом каждой сделки. Ключ на сегмент, а не на инструмент — первая '
    'такая таблица в схеме, и это не обход: величина действительно не про '
    'инструмент. Для vault-backed площадки это ближайший аналог глубины.';
comment on column vault_state.utilization_ratio is
    'Доля пула, занятая открытыми позициями, как публикует площадка. Доля, а не '
    'проценты: 0.4889 = 48.89%.';


