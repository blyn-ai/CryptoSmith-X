-- CryptoSmith X — миграция 0044: модель рынка, часы торгов, ноционал OI
-- и два набора под vault-backed площадку.
--
-- Первая площадка без книги (Avantis, perp-DEX на Base: контрагент — пул
-- ликвидности, цену даёт оракул). План — plans/avantis-connection.md, решения
-- §2 приняты владельцем, §0 отработан живьём 2026-09-11 и три его вывода
-- изменили то, что эта миграция делает. Каждый такой случай назван ниже по
-- месту: замер, а не пересказ документации.
--
-- Чего здесь НЕТ и почему — в конце файла. Коротко: колонок ставок carry, и
-- это не забывчивость.
