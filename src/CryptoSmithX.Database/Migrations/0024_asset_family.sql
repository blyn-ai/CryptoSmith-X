-- ============================================================================
-- CryptoSmith X — миграция 0024: семейство активов (уровень ПОКАЗА) и индекс по
-- паре.
--
-- ----------------------------------------------------------------------------
-- Почему семейство вообще существует
-- ----------------------------------------------------------------------------
-- Мы нормализуем базовый актив и сознательно НЕ нормализуем котировку.
--
-- Базовый актив: 0006 завёл asset/asset_alias, discovery резолвит написание
-- площадки в канон (XBT -> BTC, 1000PEPE -> PEPE с множителем 1000) и пишет обе
-- величины — base_asset (канон) и base_asset_raw (как прислала площадка).
--
-- Котировка: в DiscoveryCollector.cs стоит `QuoteAsset = i.QuoteAssetRaw` с
-- комментарием «No quote aliases in V1», и это не недосмотр, а решение самой
-- 0006: «Справочник/FK для quote_asset — в V1 котировка это фиксированное
-- USD-семейство (USD/USDT/USDC), канон = raw, отдельной таблицы активов-котировок
-- никто не спрашивает». Проверено на проде: quote_asset = quote_asset_raw ВО
-- ВСЕХ строках — USDT -> USDT 1023 инструмента, USD -> USD 509.
--
-- Отсюда следствие, ради которого пишется эта миграция: BTC/USD (Kraken) и
-- BTC/USDT (WEEX) — сегодня две разные пары. В списке пар публичной витрины они
-- были бы двумя строками, хотя человек, пришедший посмотреть на биткоин,
-- спрашивает про одну.
--
-- Свернуть их надо УРОВНЕМ ВЫШЕ канонического актива, а не внутри него, и
-- причина буквальная: канонического актива для котировки не существует. `asset`
-- — это справочник БАЗОВЫХ активов (FK exchange_instrument.base_asset ->
-- asset.code; для котировки FK нет и в 0006 от него отказались явно). На живой
-- базе `select count(*) from asset where code in ('USD','USDT','USDC')`
-- возвращает 0 и будет возвращать 0 дальше: discovery регистрирует только
-- базовые каноны (DiscoveryCollector.cs:83). Колонка family_code на `asset` не
-- смогла бы описать даже то единственное семейство, ради которого всё
-- затевается.
--
-- ----------------------------------------------------------------------------
-- Семейство — это только показ. Хранимые данные остаются строгими
-- ----------------------------------------------------------------------------
-- USDT — это USDT. Ни одна строка exchange_instrument этой миграцией не
-- меняется и не будет меняться из-за семейства: quote_asset по-прежнему равен
-- тому, что прислала площадка, и в каждой строке сравнения видна настоящая
-- котировка венью, как бы ни свернулась пара в заголовке. Семейство решает ровно
-- один вопрос — какие строки рисуются вместе под одним заголовком.
--
-- Отвергнуто: переписывать quote_asset в 'USD' при резолве, по аналогии с
-- базовым активом. Цена в USDT — не цена в USD; стирание разницы в хранимых
-- данных сделало бы её невосстановимой задним числом ради удобства одной
-- страницы. Вердикты BEST/WORST по колонкам, выраженным в котируемой валюте,
-- ранжируются внутри одной котировки именно поэтому.
--
-- ----------------------------------------------------------------------------
-- Почему ОТДЕЛЬНАЯ таблица членства, а не колонка family_code на asset
-- ----------------------------------------------------------------------------
-- Вариант «asset.family_code not null» проверяющий агент воспроизвёл на живом
-- postgres:16. DiscoveryCollector.cs:83 вставляет ровно две колонки:
--
--     insert into asset (code, note)
--     select c, 'auto-registered' from unnest(@Canons) as c
--     on conflict (code) do nothing
--
-- С NOT NULL на family_code этот insert падает —
--
--     ERROR: null value in column "family_code" of relation "asset"
--            violates not-null constraint
--
-- — и вместе с ним падает весь проход discovery: он идёт одной транзакцией,
-- открытой до вставки инструментов. Публичная витрина уронила бы сбор данных,
-- который она существует показывать. Это не гипотеза, это воспроизведённый
-- отказ.
--
-- Поэтому:
--
--   * на `asset` не добавляется ни одной колонки;
--   * членство ОПЦИОНАЛЬНО, его отсутствие читается как «семейство = сам актив»
--     (coalesce(m.family_code, i.quote_asset)), связь — только LEFT JOIN;
--   * никаких INNER JOIN на семейство в запросах. В том же отвергнутом варианте
--     внутренний join по котировке молча выбрасывал со страницы всё, что не
--     USD/USDT/USDC — без строки, без прочерка, без пометки. Исчезновение без
--     пометки — то же враньё, что ноль вместо прочерка;
--   * никаких NOT NULL и никаких внешних ключей, которые может нарушить
--     discovery. В частности НЕТ FK asset_family_member.asset_code ->
--     asset(code): он сделал бы невозможным сам сид этой миграции (строк
--     USD/USDT/USDC в `asset` нет и не будет, пока у котировки нет справочника),
--     а заодно превратил бы удаление актива в админке
--     (AssetStore.DeleteAssetAsync, который проверяет листинги и алиасы, но
--     про семейства ничего не знает) в 500 вместо строки ошибки. Код актива
--     здесь — текст, и это осознанно.
--
-- «Актив сворачивается ровно одним способом» становится фактом схемы, а не
-- соглашением: asset_code — ПЕРВИЧНЫЙ КЛЮЧ таблицы членства. Ровно одна строка
-- на актив, ровно одно семейство, второе место для той же правды не заведётся.
--
-- Цепочки (A входит в B, B входит в C) схемой не запрещены: проверка требует
-- подзапроса в CHECK, а триггеров в этой базе нет по соглашению 0001. Их
-- запрещает валидация в админке, там же, где она стоит, и сказано почему: две
-- пересадки означают, что актив сворачивается двумя способами.
--
-- ----------------------------------------------------------------------------
-- Что НЕ вошло и почему
-- ----------------------------------------------------------------------------
--   * Семейства базовых активов (WBTC/BTC, stETH/ETH). Схема их допускает —
--     таблица ключуется кодом актива, а не «кодом котировки», — но сидов нет:
--     заворачивать обёрнутый токен в базовый актив это утверждение о рынке, а не
--     о показе, и его должен сделать человек, а не миграция.
--   * Массив кодов на строке семейства вместо таблицы членства. Тогда «ровно
--     один способ» пришлось бы проверять по всем строкам сразу, а не первичным
--     ключом, и админка правила бы массив целиком вместо одной строки.
--   * Признак «главный актив семейства» (какой код показывать в заголовке).
--     Заголовок берёт код семейства, он для того и есть; вторая колонка с тем же
--     смыслом разъедется с первой.
--
-- ----------------------------------------------------------------------------
-- Индекс по паре
-- ----------------------------------------------------------------------------
-- Все публичные запросы витрины группируют и фильтруют по (base_asset,
-- quote_asset) и все несут `and i.collect` — потому что показывать инструмент,
-- по которому мы ничего не собираем, значит обещать данные, которых нет.
-- Поэтому индекс частичный: он покрывает ровно тот набор строк, который эти
-- запросы читают, и не платит за остальные.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. Справочник семейств
-- ----------------------------------------------------------------------------
create table asset_family (
    code       text        primary key,   -- 'USD' — код семейства, он же заголовок пары
    name       text,
    note       text,
    created_at timestamptz not null default now(),
    updated_at timestamptz,               -- выставляет приложение, как у asset (0008)
    updated_by text
);

comment on table asset_family is
    'Семейство активов — уровень ПОКАЗА над каноническим активом. Существует потому, что '
    'котировка не нормализуется (quote_asset = quote_asset_raw во всех строках), и BTC/USD с '
    'BTC/USDT иначе были бы двумя строками списка пар. На хранимые данные не влияет: '
    'exchange_instrument.quote_asset остаётся тем, что прислала площадка.';

comment on column asset_family.code is
    'Код семейства. Показывается как котировка пары в заголовке; строка сравнения при этом '
    'всё равно показывает настоящую котировку своей площадки.';


-- ----------------------------------------------------------------------------
-- 2. Членство. Ключ — код актива: ровно одна строка на актив
-- ----------------------------------------------------------------------------
-- asset_code БЕЗ FK на asset(code) — обоснование в шапке: справочника активов
-- для котировок не существует, сид этой миграции сам бы такой FK и нарушил.
create table asset_family_member (
    asset_code  text        primary key,                         -- 'USDT' — как оно лежит в exchange_instrument
    family_code text        not null references asset_family (code),
    note        text,
    created_at  timestamptz not null default now(),
    created_by  text
);

comment on table asset_family_member is
    'Членство актива в семействе. ОПЦИОНАЛЬНО: отсутствие строки читается как «семейство = сам '
    'актив», поэтому читать только через coalesce и только LEFT JOIN. Первичный ключ по '
    'asset_code делает фактом схемы то, что актив сворачивается ровно одним способом. '
    'FK на asset(code) нет намеренно: активов-котировок в справочнике активов не бывает.';

comment on column asset_family_member.asset_code is
    'Код актива ровно в том написании, в каком он лежит в exchange_instrument (base_asset или '
    'quote_asset). Сравнение точное, поэтому регистр значим.';

comment on column asset_family_member.family_code is
    'Куда сворачивается. NOT NULL здесь безопасен: в эту таблицу пишет только админка, '
    'discovery её не видит. Строка без семейства не значила бы ничего — её просто не должно быть.';

-- Обратный обход «кто входит в семейство» — и в админке, и в запросах витрины.
create index asset_family_member_family on asset_family_member (family_code);


-- ----------------------------------------------------------------------------
-- 3. Сид: долларовое семейство
-- ----------------------------------------------------------------------------
insert into asset_family (code, name, note) values
    ('USD', 'US dollar', 'USD, USDT, USDC сворачиваются в одну пару. Состав правится в админке.')
on conflict (code) do nothing;

-- Строка USD -> USD избыточна: без неё coalesce дал бы тот же ответ. Она стоит
-- здесь намеренно — состав семейства должен читаться как данные, а не
-- выводиться из отсутствия записи. Тому, кто откроет админку, «USD, USDT, USDC»
-- и «USDT, USDC» это два разных утверждения.
insert into asset_family_member (asset_code, family_code, note) values
    ('USD',  'USD', 'сид 0024'),
    ('USDT', 'USD', 'сид 0024'),
    ('USDC', 'USD', 'сид 0024')
on conflict (asset_code) do nothing;


-- ----------------------------------------------------------------------------
-- 4. Индекс по паре
-- ----------------------------------------------------------------------------
create index exchange_instrument_pair on exchange_instrument (base_asset, quote_asset) where collect;

comment on index exchange_instrument_pair is
    'Список пар и страница пары ходят по (base_asset, quote_asset) и всегда с and collect. '
    'Частичный именно поэтому: покрывает ровно те строки, которые витрина читает.';
